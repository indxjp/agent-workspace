#!/usr/bin/env bash
# R-02 — the Ubuntu 24.04 counterfactual, run instead of predicted.
#
# Round 2 of the note asserted, without trying, that swapping
# `IMAGE=ubuntu:24.04` into `probe-linux.sh` "would not reproduce" the failure
# that issues #428 and #429 report, "it would produce a Debian-shaped pass under
# an Ubuntu userland". That prediction is what this script tests.
#
# It matters because #428's own body says the cause is NOT AppArmor: it names
# `bwrap` 0.9.0 — the version Ubuntu 24.04 ships — clearing the capability
# bounding set. A bwrap version lives in the IMAGE, not in the host kernel, so
# an Ubuntu 24.04 image on any kernel is the right place to look for it.
#
# Writes `probe-ubuntu2404.txt` next to this script.
#
# Usage:
#   bash probe-ubuntu2404.sh
#
# Exits 0 always; it is a report, not a pass/fail gate.

set -uo pipefail
cd "$(dirname "$0")"

OUT="probe-ubuntu2404.txt"

read -r -d '' BODY <<'INNER'
set -uo pipefail
hr() { echo; echo "== $* =="; }

hr "platform"
uname -a
grep -E '^(PRETTY_NAME|VERSION_ID)=' /etc/os-release

hr "the AppArmor sysctl #429 and #428 both report as 0 in their environments"
echo '$ cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns'
cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>&1
echo "exit code: $?"

hr "install prerequisites and the CLI"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq >/dev/null 2>&1
apt-get install -y -qq bubblewrap socat ripgrep curl ca-certificates xz-utils >/dev/null 2>&1
echo "apt-get rc=$?"
# Ubuntu 24.04's own `nodejs` package is v18, below this package's declared
# engines (>=20.11.0). Node 20 is installed from nodejs.org instead so the run
# cannot be dismissed as an engines mismatch: the only Ubuntu-specific things
# under test are the userland and `bwrap` 0.9.0.
curl -fsSL -o /tmp/node.tar.xz https://nodejs.org/dist/v20.20.2/node-v20.20.2-linux-x64.tar.xz 2>/dev/null
echo "node tarball fetch rc=$?"
mkdir -p /opt/node && tar -xJf /tmp/node.tar.xz -C /opt/node --strip-components=1
export PATH=/opt/node/bin:$PATH
echo "node: $(node --version 2>&1)"
echo "npm:  $(npm --version 2>&1)"
echo '$ bwrap --version    # #428 names 0.9.0 as the version Ubuntu 24.04 ships'
bwrap --version 2>&1
npm install -g @anthropic-ai/sandbox-runtime >/dev/null 2>&1
echo "npm install -g rc=$?"
SRT_PKG="$(npm root -g 2>/dev/null)/@anthropic-ai/sandbox-runtime/package.json"
echo "installed package version: $(node -e "console.log(require('$SRT_PKG').version)" 2>&1)"

hr "bwrap on its own (issue #417 / #428 use this as their control)"
echo '$ bwrap --ro-bind / / --unshare-all --die-with-parent /bin/true'
bwrap --ro-bind / / --unshare-all --die-with-parent /bin/true 2>&1
echo "exit code: $?"

hr "settings files"
mkdir -p /tmp/work
cat > /tmp/s-false.json <<'JSON'
{
  "filesystem": { "allowRead": [], "denyRead": [], "allowWrite": ["/tmp/work"], "denyWrite": [] },
  "network": { "allowedDomains": [], "deniedDomains": [] },
  "enableWeakerNestedSandbox": false
}
JSON
cat > /tmp/s-true.json <<'JSON'
{
  "filesystem": { "allowRead": [], "denyRead": [], "allowWrite": ["/tmp/work"], "denyWrite": [] },
  "network": { "allowedDomains": [], "deniedDomains": [] },
  "enableWeakerNestedSandbox": true
}
JSON
echo "wrote /tmp/s-false.json and /tmp/s-true.json"

hr "EXEC PROBE — enableWeakerNestedSandbox: false"
echo '$ srt --settings /tmp/s-false.json -c "echo hi"'
srt --settings /tmp/s-false.json -c 'echo hi' 2>&1
echo "exit code: $?"

hr "EXEC PROBE — enableWeakerNestedSandbox: true"
echo '$ srt --settings /tmp/s-true.json -c "echo hi"'
srt --settings /tmp/s-true.json -c 'echo hi' 2>&1
echo "exit code: $?"

hr "done"
echo "ubuntu 24.04 probe complete"
INNER

echo "docker info:"
docker info --format 'ServerVersion={{.ServerVersion}} OSType={{.OSType}} OperatingSystem={{.OperatingSystem}}'

for mode in unprivileged privileged; do
  if [ "$mode" = "privileged" ]; then priv=(--privileged); else priv=(); fi
  {
    echo "# Generated by probe-ubuntu2404.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# host: $(uname -s -r)"
    echo "# docker: $(docker info --format 'ServerVersion={{.ServerVersion}} OSType={{.OSType}} OperatingSystem={{.OperatingSystem}}')"
    echo "# command: docker run --rm -i ${priv[*]:-} ubuntu:24.04 bash -s"
    echo
    echo "########## MODE=$mode ##########"
    MSYS_NO_PATHCONV=1 docker run --rm -i "${priv[@]}" ubuntu:24.04 bash -s <<<"$BODY" 2>&1
  }
done > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
