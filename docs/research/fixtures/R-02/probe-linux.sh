#!/usr/bin/env bash
# R-02 Linux probe — host-side wrapper.
#
# Runs `probe-linux-in-container.sh` twice inside a throwaway Debian-based
# `node:20` container, once with Docker's default (unprivileged) profile and
# once with `--privileged`, and writes the two raw transcripts next to this
# script:
#
#   probe-linux-unprivileged.txt   MODE=unprivileged
#   probe-linux-privileged.txt     MODE=privileged
#
# `node:20` is the image upstream issue #180 names in its own reproduction
# ("docker run -it --rm node:20 bash"), which is why it is the image here.
#
# The two modes exist because they answer different questions:
#   unprivileged — reproduces issue #180: does `enableWeakerNestedSandbox`
#                  rescue a plain unprivileged container? (No.)
#   privileged   — gives bubblewrap the namespaces it needs, so the exec,
#                  filesystem, network, TLS, device and startup-latency probes
#                  can actually run and be observed.
#
# Requirements: Docker with a Linux engine (`docker info` must report
# `OSType: linux`; on Windows that is Docker Desktop's WSL2 VM) and network
# access to the Debian archive and the npm registry from inside the container.
# Nothing is installed on the host: every apt-get and npm install happens
# inside the `--rm` container and is discarded with it.
#
# Usage:
#   bash probe-linux.sh
#
# Exits 0 always; it is a report, not a pass/fail gate.

set -uo pipefail
cd "$(dirname "$0")"

IMAGE="${IMAGE:-node:20}"

echo "docker info:"
docker info --format 'ServerVersion={{.ServerVersion}} OSType={{.OSType}} OperatingSystem={{.OperatingSystem}}'
echo

for mode in unprivileged privileged; do
  out="probe-linux-${mode}.txt"
  if [ "$mode" = "privileged" ]; then
    priv=(--privileged)
  else
    priv=()
  fi
  echo "== running MODE=$mode -> $out =="
  {
    echo "# Generated by probe-linux.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "# host: $(uname -s -r)"
    echo "# docker: $(docker info --format 'ServerVersion={{.ServerVersion}} OSType={{.OSType}} OperatingSystem={{.OperatingSystem}}')"
    echo "# command: docker run --rm -i ${priv[*]:-} -e MODE=$mode $IMAGE bash -s < probe-linux-in-container.sh"
    # MSYS_NO_PATHCONV stops git-bash rewriting the container-side paths in
    # the script's arguments; it is a no-op on Linux and macOS shells.
    MSYS_NO_PATHCONV=1 docker run --rm -i "${priv[@]}" -e "MODE=$mode" "$IMAGE" bash -s < probe-linux-in-container.sh 2>&1
  } > "$out"
  echo "wrote $out ($(wc -l < "$out") lines)"
done
