#!/usr/bin/env bash
# R-02 Linux probe, ROUND 3 — host-side wrapper.
#
# Runs `probe-linux-r3-in-container.sh` once, inside a throwaway `--privileged`
# `node:20` container, and writes the transcript next to this script:
#
#   probe-linux-r3-privileged.txt
#
# It is a supplement to `probe-linux.sh`, not a replacement: that script's two
# transcripts remain the evidence for Findings 2, 5, 6 and 9. This one adds the
# sections round 2 of the note graded without running — see the header of
# `probe-linux-r3-in-container.sh` for the list.
#
# Only the privileged mode is run. The unprivileged question ("does
# `enableWeakerNestedSandbox` rescue a plain container?") is already answered by
# `probe-linux-unprivileged.txt` and nothing here would add to it: no sandboxed
# command runs at all in that mode.
#
# Requirements: Docker with a Linux engine (`docker info` must report
# `OSType: linux`) and network access to the Debian archive and the npm registry
# from inside the container. Nothing is installed on the host.
#
# Usage:
#   bash probe-linux-r3.sh
#
# Exits 0 always; it is a report, not a pass/fail gate.

set -uo pipefail
cd "$(dirname "$0")"

IMAGE="${IMAGE:-node:20}"
OUT="probe-linux-r3-privileged.txt"

echo "docker info:"
docker info --format 'ServerVersion={{.ServerVersion}} OSType={{.OSType}} OperatingSystem={{.OperatingSystem}}'
echo

echo "== running -> $OUT =="
{
  echo "# Generated by probe-linux-r3.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# host: $(uname -s -r)"
  echo "# docker: $(docker info --format 'ServerVersion={{.ServerVersion}} OSType={{.OSType}} OperatingSystem={{.OperatingSystem}}')"
  echo "# command: docker run --rm -i --privileged $IMAGE bash -s < probe-linux-r3-in-container.sh"
  # MSYS_NO_PATHCONV stops git-bash rewriting container-side paths; a no-op on
  # Linux and macOS shells.
  MSYS_NO_PATHCONV=1 docker run --rm -i --privileged "$IMAGE" bash -s < probe-linux-r3-in-container.sh 2>&1
} > "$OUT"
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
