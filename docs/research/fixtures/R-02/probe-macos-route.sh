#!/usr/bin/env bash
# R-02 — the macOS-route check, made reviewable.
#
# Round 2 of the note quoted the outputs of a macOS-availability attempt in its
# Declared gaps section while committing none of them, contradicting the note's
# own provenance sentence. This script is that attempt, so the outputs the note
# quotes for its largest declared gap can be diffed against a transcript like
# every other quotation in it.
#
# It runs read-only checks on the research workstation plus two `--rm` container
# reads. It installs nothing and starts no hypervisor.
#
# Writes `probe-macos-route.txt` next to this script.
#
# Usage:
#   bash probe-macos-route.sh
#
# Exits 0 always; it is a report, not a pass/fail gate.

set -uo pipefail
cd "$(dirname "$0")"

OUT="probe-macos-route.txt"

{
  echo "# Generated by probe-macos-route.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# host: $(uname -s -r -m)"
  echo

  echo "== is Apple's sandbox-exec available here? =="
  echo '$ command -v sandbox-exec'
  if command -v sandbox-exec >/dev/null 2>&1; then
    echo "sandbox-exec: found at $(command -v sandbox-exec)"
  else
    echo "sandbox-exec: NOT found on PATH"
  fi
  echo "exit code: $?"

  echo
  echo "== is any local hypervisor that could host macOS installed? =="
  for h in VBoxManage qemu-system-x86_64 vmrun prlctl UTM; do
    if command -v "$h" >/dev/null 2>&1; then
      echo "$h: found at $(command -v "$h")"
    else
      echo "$h: not found"
    fi
  done

  echo
  echo "== does the Docker engine offer any Darwin platform? =="
  echo '$ docker buildx ls'
  docker buildx ls 2>&1
  echo "exit code: $?"

  echo
  echo "== the AppArmor sysctl issues #429/#428 list in their environments, on THIS kernel =="
  echo '$ docker run --rm --privileged node:20 cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns'
  MSYS_NO_PATHCONV=1 docker run --rm --privileged node:20 cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>&1
  echo "exit code: $?"

  echo
  echo '$ docker run --rm --privileged ubuntu:24.04 cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns'
  MSYS_NO_PATHCONV=1 docker run --rm --privileged ubuntu:24.04 cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>&1
  echo "exit code: $?"

  echo
  echo "== done =="
} > "$OUT" 2>&1
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
