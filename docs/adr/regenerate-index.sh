#!/bin/sh
# Regenerate the index block in docs/adr/README.md from the directory itself.
#
# This file exists because the index has drifted three times: the table is written by hand,
# nothing derives it, and every repair so far corrected the number rather than the mechanism
# that produced the wrong number. Per docs/adr/W0-DOC-01-mechanical-count-derivation.md, a
# count in governance prose names the command that produced it — so here is the command, in
# the tree, runnable, next to the thing it produces.
#
#   sh docs/adr/regenerate-index.sh            rewrite the block in README.md in place
#   sh docs/adr/regenerate-index.sh --check    exit 1 if the block is stale; print the diff
#   sh docs/adr/regenerate-index.sh --print    write the block to stdout, touch nothing
#
# --check compares the ROWS and the COUNT only, never the provenance stamp. The stamp names
# the commit the generator read; it necessarily goes stale the moment anything else is
# committed, and a check that failed on that would be noise. The rows are the assertion.
#
# Run from anywhere: paths are resolved against this script's own directory.

set -eu

adr_dir=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
readme="$adr_dir/README.md"
begin='<!-- BEGIN GENERATED INDEX -->'
end='<!-- END GENERATED INDEX -->'

mode=write
case "${1-}" in
  --check) mode=check ;;
  --print) mode=print ;;
  '') ;;
  *) echo "usage: $0 [--check|--print]" >&2; exit 2 ;;
esac

# --- the derivation ------------------------------------------------------------------------
# Reads all three header shapes present in this directory: `Status:` / `Date:` / `Scope:` on
# their own lines (programme records), the `· `-separated single line (W0-DOC-01), and the
# `- **Status:**` list form (the W0-INF-01 and W0-INF-02 task records). An earlier command in
# this slot grepped `^(Status|Date|Scope):`, which the task records do not match, so it emitted
# a title and nothing else for nine files — part of why the table drifted.

records() {
  ls "$adr_dir"/*.md | grep -v README | sort
}

rows() {
  records | while read -r f; do
    b=$(basename "$f" .md)
    id=$(printf '%s' "$b" | sed -E 's/^(W[0-9]+-[A-Z]+-[0-9]+|[0-9]{4})-.*/\1/')
    title=$(head -1 "$f" | tr -d '\r' | sed -E 's/^# +//; s/^[^ ]+ +(—|·|-) +//')
    meta=$(sed -n '1,12p' "$f" | tr -d '\r')
    status=$(printf '%s\n' "$meta" | sed -nE 's/.*[Ss]tatus:?\*{0,2}:? *([^·|]*).*/\1/p' |
      head -1 | sed 's/ *$//; s/^Accepted/accepted/')
    date=$(printf '%s\n' "$meta" |
      sed -nE 's/.*[Dd]ate:?\*{0,2}:? *([0-9]{4}-[0-9]{2}-[0-9]{2}).*/\1/p' | head -1)
    scope=$(printf '%s\n' "$meta" | sed -nE 's/^Scope: *//p' | head -1)
    [ -n "$scope" ] || scope=$(printf '%s\n' "$meta" |
      sed -nE 's/^[-* ]*\*\*Context task:\*\* *//p' | head -1 | sed 's/^/task /')
    [ -n "$scope" ] || scope=$(printf '%s\n' "$meta" |
      sed -nE 's/.*Task: *([^·]*).*/task \1/p' | head -1 | sed 's/ *$//')
    printf '| [%s](%s) | %s | %s | %s | %s |\n' "$id" "$(basename "$f")" "$title" "$date" \
      "$scope" "$status"
  done
}

# The count is `wc -l` over the same listing the rows come from, so the number and the table
# cannot disagree by construction — that is the whole point of generating them together.
count=$(records | wc -l | tr -d ' ')

provenance() {
  sha=$(git -C "$adr_dir" rev-parse --short HEAD 2>/dev/null || echo 'no-git')
  # Anything staged or unstaged under docs/adr other than README.md means the listing the
  # generator read is not the listing at $sha. Say so rather than stamping a commit that does
  # not contain what was measured.
  dirty=$(git -C "$adr_dir" status --porcelain -- "$adr_dir" 2>/dev/null |
    grep -v 'docs/adr/README\.md$' | wc -l | tr -d ' ')
  [ "$dirty" = "0" ] || sha="$sha+$dirty uncommitted"
  printf '%s, %s' "$sha" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}

block() {
  printf '%s\n' "$begin"
  printf '**%s records** in `docs/adr/`.\n' "$count"
  printf '\n'
  printf '_Generated by `docs/adr/regenerate-index.sh`; the tree it read was %s._\n' "$(provenance)"
  printf '\n'
  printf 'Do not edit the table by hand and do not correct the number by hand — run the script.\n'
  printf '\n'
  printf '| Id | Title | Date | Scope | Status |\n'
  printf '| --- | --- | --- | --- | --- |\n'
  rows
  printf '%s\n' "$end"
}

# --- comparison and rewrite ----------------------------------------------------------------
# Strip ONLY the provenance line, so --check is about the records rather than about how long ago
# the generator last ran. The COUNT is deliberately NOT stripped: it is the assertion this file
# kept getting wrong, and a check that skipped it would happily pass a hand-corrected number
# sitting above a stale table — the same shape of hole this script exists to close. The stamp is
# one line and it is the only line beginning `_Generated by `.
without_stamp() {
  grep -v '^_Generated by '
}

extract_current() {
  sed -n "/^$(printf '%s' "$begin" | sed 's/[]\/$*.^[]/\\&/g')\$/,/^$(printf '%s' "$end" | sed 's/[]\/$*.^[]/\\&/g')\$/p" "$readme"
}

if [ "$mode" = print ]; then
  block
  exit 0
fi

if ! grep -qF "$begin" "$readme" || ! grep -qF "$end" "$readme"; then
  echo "regenerate-index.sh: $readme has no generated-index markers" >&2
  exit 2
fi

tmp_new=$(mktemp) || exit 1
tmp_old=$(mktemp) || exit 1
trap 'rm -f "$tmp_new" "$tmp_old"' EXIT

block | without_stamp >"$tmp_new"
extract_current | without_stamp >"$tmp_old"

if [ "$mode" = check ]; then
  if diff -u "$tmp_old" "$tmp_new" >/dev/null; then
    echo "docs/adr/README.md index is current: $count records."
    exit 0
  fi
  echo "docs/adr/README.md index is STALE. Run: sh docs/adr/regenerate-index.sh" >&2
  diff -u "$tmp_old" "$tmp_new" >&2 || true
  exit 1
fi

# Rewrite: everything before the opening marker, the fresh block, everything after the closing
# one. The block file is read by awk rather than interpolated, so a `&` or a backslash in an
# ADR title cannot be re-interpreted on the way in.
tmp_blk=$(mktemp) || exit 1
tmp_out=$(mktemp) || exit 1
trap 'rm -f "$tmp_new" "$tmp_old" "$tmp_blk" "$tmp_out"' EXIT
block >"$tmp_blk"

awk -v b="$begin" -v e="$end" -v blkfile="$tmp_blk" '
  $0 == b { while ((getline line < blkfile) > 0) print line; close(blkfile); skip = 1; next }
  $0 == e { skip = 0; next }
  !skip   { print }
' "$readme" >"$tmp_out"

cat "$tmp_out" >"$readme"
echo "docs/adr/README.md regenerated: $count records."
