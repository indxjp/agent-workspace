#!/usr/bin/env node
/**
 * Generates everything derived from the Lean specification (docs/adr/0062):
 *
 * - `formal/generated/catalogue.json` — every `@[aw_spec]` declaration (`lake exe catalogue`);
 * - `formal/generated/vectors/**` — the differential test vectors (`lake exe vectors`);
 * - `docs/formal/catalogue.md` — the theorem catalogue, grouped by tier and family, with counts;
 * - `docs/formal/traceability.md` — document anchor ↔ Lean name ↔ TypeScript symbol ↔ test;
 * - `formal/generated/ErSnapshot.lean` — the ER snapshot pins (the latest migration's snapshot
 *   file, its table names and its column, foreign-key, unique-key and check totals), read from
 *   `migrations/meta/_journal.json` and that snapshot. It is written before `lake` runs, because
 *   the model imports it.
 *
 * Every citation is validated while rendering: a `doc` citation's file must exist and its
 * `#anchor` must be a heading of that file; a `ts` citation's file must exist and, for source
 * files, declare its `#symbol` (see `declaredNames`: a mention in a comment, an import or a use
 * does not count); a data file (`.sql`, `.tf`, `.json`) must contain it as a word. `--write` rewrites the outputs; `--check` renders into memory (and the
 * Lean outputs into a temporary directory) and fails on any difference, as `docs:check` does.
 * `--no-lake` skips the two Lean executables and renders from the committed JSON.
 */
import console from 'node:console';
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import ts from 'typescript';

import { FORMAL_ROOT, REPOSITORY_ROOT, runLake } from './lake.mjs';

const CATALOGUE_JSON = path.join(FORMAL_ROOT, 'generated', 'catalogue.json');
const VECTORS_DIR = path.join(FORMAL_ROOT, 'generated', 'vectors');
const CATALOGUE_MD = path.join(REPOSITORY_ROOT, 'docs', 'formal', 'catalogue.md');
const TRACEABILITY_MD = path.join(REPOSITORY_ROOT, 'docs', 'formal', 'traceability.md');
const ER_SNAPSHOT_LEAN = path.join(FORMAL_ROOT, 'generated', 'ErSnapshot.lean');
const MIGRATIONS_META = path.join(REPOSITORY_ROOT, 'migrations', 'meta');
const TIERS = ['T0', 'T1', 'T2', 'T3', 'T4', 'T5'];
const TIER_NAMES = {
  T0: 'Well-formedness',
  T1: 'Normative',
  T2: 'Invariants',
  T3: 'Adversarial',
  T4: 'Refinement',
  T5: 'Meta',
};
const BANNER =
  '<!-- Generated by scripts/formal/generate.mjs from formal/generated/catalogue.json. Do not edit; run `pnpm formal:generate`. -->';

/**
 * @typedef {{ name: string, module: string, kind: string, tier: string | null,
 *   doc: string[], ts: string[], docstring: string, statement: string }} Entry
 */

/** @param {string} relative */
function repositoryFile(relative) {
  return path.join(REPOSITORY_ROOT, ...relative.split('/'));
}

/** @param {string} directory @returns {string[]} */
function listFiles(directory) {
  /** @type {string[]} */
  const files = [];
  for (const name of readdirSync(directory).sort()) {
    const full = path.join(directory, name);
    if (statSync(full).isDirectory()) files.push(...listFiles(full));
    else files.push(full);
  }
  return files;
}

/**
 * GitHub-style heading slugs (lower case, punctuation dropped, each space a hyphen, duplicates
 * suffixed `-1`, `-2`, …), which is what both GitHub and Mintlify anchor.
 * @param {string} source
 */
function headingSlugs(source) {
  /** @type {Map<string, number>} */
  const seen = new Map();
  const slugs = new Set();
  let fenced = false;
  for (const line of source.split(/\r?\n/u)) {
    if (/^\s*(```|~~~)/u.test(line)) fenced = !fenced;
    if (fenced) continue;
    const match = /^#{1,6}\s+(.+?)\s*#*\s*$/u.exec(line);
    if (match === null) continue;
    const base = (match[1] ?? '')
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s_-]/gu, '')
      .replace(/ /gu, '-');
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    slugs.add(count === 0 ? base : `${base}-${String(count)}`);
  }
  return slugs;
}

/** @type {Map<string, string>} */
const fileCache = new Map();
/** @param {string} relative @returns {string | null} */
function readCited(relative) {
  const cached = fileCache.get(relative);
  if (cached !== undefined) return cached;
  let contents;
  try {
    contents = readFileSync(repositoryFile(relative), 'utf8');
  } catch {
    return null;
  }
  fileCache.set(relative, contents);
  return contents;
}

/** @param {string} citation */
function splitCitation(citation) {
  const hash = citation.indexOf('#');
  return hash < 0
    ? { file: citation, fragment: '' }
    : { file: citation.slice(0, hash), fragment: citation.slice(hash + 1) };
}

/** @param {string} symbol */
function escapeRegExp(symbol) {
  return symbol.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
}

const SOURCE_FILE = /\.[cm]?[jt]sx?$/u;

const DATABASE_OBJECT_BUILDERS =
  /^(?:check|index|uniqueIndex|unique|primaryKey|pgTable|pgEnum|oneOf)$/u;

/**
 * A string literal that names a database object in a Drizzle schema: the first argument of
 * `check('name', …)`, `index('name')`, `uniqueIndex('name')`, or the `name` of a `foreignKey({…})`.
 * @param {ts.StringLiteralLike} node
 */
function namesDatabaseObject(node) {
  const parent = node.parent;
  if (ts.isCallExpression(parent)) {
    return (
      DATABASE_OBJECT_BUILDERS.test(parent.expression.getText()) && parent.arguments[0] === node
    );
  }
  return (
    ts.isPropertyAssignment(parent) && ts.isIdentifier(parent.name) && parent.name.text === 'name'
  );
}

/**
 * What a source file declares, read from its syntax tree so that comments, imports and plain uses
 * never count. `names` holds, at any depth, the name of every function, class, interface, type
 * alias, enum, namespace and variable binding, every member of a declared type (class, interface,
 * type literal, enum), every local export name (`export { a as b }`), every property of an object
 * literal (a composition root's wiring, a table's columns), and every string literal that
 * names a database object (`namesDatabaseObject`). `strings` holds the text
 * of every string literal, which the few citations of a CLI command or flag (`runs wait`) resolve
 * against because they are not identifiers.
 * @param {string} file
 * @param {string} source
 * @returns {{ names: Set<string>, strings: Set<string> }}
 */
function declaredNames(file, source) {
  const names = new Set();
  const strings = new Set();
  /** @param {ts.Node | undefined} name */
  const addName = (name) => {
    if (name === undefined) return;
    if (ts.isIdentifier(name) || ts.isStringLiteral(name) || ts.isPrivateIdentifier(name)) {
      names.add(name.text);
    } else if (ts.isObjectBindingPattern(name) || ts.isArrayBindingPattern(name)) {
      for (const element of name.elements) {
        if (ts.isBindingElement(element)) addName(element.name);
      }
    }
  };
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  /** @param {ts.Node} node */
  const visit = (node) => {
    if (ts.isStringLiteralLike(node)) strings.add(node.text);
    if (
      ts.isFunctionDeclaration(node) ||
      ts.isClassDeclaration(node) ||
      ts.isInterfaceDeclaration(node) ||
      ts.isTypeAliasDeclaration(node) ||
      ts.isEnumDeclaration(node) ||
      ts.isModuleDeclaration(node) ||
      ts.isVariableDeclaration(node) ||
      ts.isPropertyDeclaration(node) ||
      ts.isMethodDeclaration(node) ||
      ts.isGetAccessorDeclaration(node) ||
      ts.isSetAccessorDeclaration(node) ||
      ts.isPropertySignature(node) ||
      ts.isMethodSignature(node) ||
      ts.isEnumMember(node)
    ) {
      addName(node.name);
    } else if (ts.isExportSpecifier(node)) {
      names.add(node.name.text);
    } else if (ts.isPropertyAssignment(node) || ts.isShorthandPropertyAssignment(node)) {
      addName(node.name);
    } else if (ts.isStringLiteralLike(node) && namesDatabaseObject(node)) {
      names.add(node.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return { names, strings };
}

/** @type {Map<string, { names: Set<string>, strings: Set<string> }>} */
const declarationCache = new Map();

/**
 * @param {string} file
 * @param {string} source
 * @param {string} fragment
 */
function isCitedSymbolDeclared(file, source, fragment) {
  if (!SOURCE_FILE.test(file)) {
    return new RegExp(`(?<![\\w$])${escapeRegExp(fragment)}(?![\\w$])`, 'u').test(source);
  }
  let declared = declarationCache.get(source);
  if (declared === undefined) {
    declared = declaredNames(file, source);
    declarationCache.set(source, declared);
  }
  return /^[\w$]+$/u.test(fragment) ? declared.names.has(fragment) : declared.strings.has(fragment);
}

/**
 * @param {readonly Entry[]} entries
 * @param {(relative: string) => string | null} [read]
 * @returns {string[]}
 */
export function citationFailures(entries, read = readCited) {
  /** @type {string[]} */
  const failures = [];
  for (const entry of entries) {
    for (const citation of entry.doc) {
      const { file, fragment } = splitCitation(citation);
      const source = read(file);
      if (source === null) failures.push(`${entry.name}: doc ${citation}: no such file`);
      else if (fragment !== '' && !headingSlugs(source).has(fragment)) {
        failures.push(`${entry.name}: doc ${citation}: no heading with that anchor`);
      }
    }
    for (const citation of entry.ts) {
      const { file, fragment } = splitCitation(citation);
      const source = read(file);
      if (source === null) failures.push(`${entry.name}: ts ${citation}: no such file`);
      else if (fragment !== '' && !isCitedSymbolDeclared(file, source, fragment)) {
        failures.push(`${entry.name}: ts ${citation}: symbol not declared in the file`);
      }
    }
  }
  return failures;
}

/** The family of a declaration: the last component of its module name. @param {Entry} entry */
function familyOf(entry) {
  return entry.module.split('.').at(-1) ?? entry.module;
}

/** @param {string} text */
function cell(text) {
  return text.replace(/\|/gu, '\\|').replace(/\r?\n/gu, ' ');
}

/** @param {string} name */
function shortName(name) {
  return name.replace(/^AgentWorkspace\./u, '');
}

/** @param {string} citation */
function citationLink(citation) {
  return `\`${citation}\``;
}

/** @param {readonly Entry[]} entries */
function renderCatalogue(entries) {
  const theorems = entries.filter((e) => e.tier !== null);
  const definitions = entries.filter((e) => e.tier === null);
  const families = [...new Set(theorems.map(familyOf))].sort();
  const cited = theorems.filter((e) => e.doc.length > 0).length;
  const lines = [
    '# Formal specification catalogue',
    '',
    BANNER,
    '',
    'Every theorem and traced definition of the Lean model in `formal/`, grouped by tier (docs/formal/00-orchestrator-prompt.md §6) and family. Statements are the Lean types; the sentence under each is its docstring.',
    '',
    '## Counts',
    '',
    `| Family | ${TIERS.join(' | ')} | Total |`,
    `| --- | ${TIERS.map(() => '---:').join(' | ')} | ---: |`,
  ];
  for (const family of families) {
    const row = TIERS.map(
      (tier) => theorems.filter((e) => familyOf(e) === family && e.tier === tier).length,
    );
    lines.push(
      `| ${family} | ${row.map(String).join(' | ')} | ${String(row.reduce((a, b) => a + b, 0))} |`,
    );
  }
  const totals = TIERS.map((tier) => theorems.filter((e) => e.tier === tier).length);
  lines.push(
    `| **All** | ${totals.map(String).join(' | ')} | ${String(theorems.length)} |`,
    '',
    `- Theorems: ${String(theorems.length)}; traced definitions: ${String(definitions.length)}.`,
    `- Theorems citing a document: ${String(cited)} of ${String(theorems.length)}.`,
    '',
  );
  for (const tier of TIERS) {
    const inTier = theorems.filter((e) => e.tier === tier);
    lines.push(`## ${tier} — ${TIER_NAMES[/** @type {keyof typeof TIER_NAMES} */ (tier)]}`, '');
    if (inTier.length === 0) {
      lines.push('None yet.', '');
      continue;
    }
    for (const family of [...new Set(inTier.map(familyOf))].sort()) {
      lines.push(`### ${tier} · ${family}`, '');
      for (const entry of inTier.filter((e) => familyOf(e) === family)) {
        lines.push(
          `- **\`${shortName(entry.name)}\`** — ${entry.docstring.replace(/\s+/gu, ' ')}`,
          `  - Statement: \`${entry.statement}\``,
        );
        const cites = [...entry.doc, ...entry.ts];
        if (cites.length > 0) lines.push(`  - Cites: ${cites.map(citationLink).join(', ')}`);
      }
      lines.push('');
    }
  }
  lines.push('## Traced definitions', '');
  lines.push('| Definition | Kind | Cites |', '| --- | --- | --- |');
  for (const entry of definitions) {
    lines.push(
      `| \`${shortName(entry.name)}\` | ${entry.kind} | ${cell([...entry.doc, ...entry.ts].map(citationLink).join(', '))} |`,
    );
  }
  return `${lines.join('\n')}\n`;
}

/** @param {Map<string, string>} vectorFiles */
function witnessTests(vectorFiles) {
  /** @type {Map<string, Set<string>>} */
  const tests = new Map();
  for (const [relative, contents] of vectorFiles) {
    const family = relative.split('/')[0] ?? '';
    // A family replayed against package code lives in tests/formal/; one replayed against an
    // application's server code lives in that application's own project (apps/<app>/formal/).
    const test = [
      `tests/formal/${family}.test.ts`,
      `apps/web/formal/${family}.test.ts`,
      `apps/runner/formal/${family}.test.ts`,
    ].find((candidate) => readCited(candidate) !== null);
    if (test === undefined) continue;
    /** @type {{ vectors?: { witnesses?: string[] }[] }} */
    const parsed = JSON.parse(contents);
    for (const vector of parsed.vectors ?? []) {
      for (const witness of vector.witnesses ?? []) {
        const set = tests.get(witness) ?? new Set();
        set.add(test);
        tests.set(witness, set);
      }
    }
  }
  return tests;
}

/** @param {readonly Entry[]} entries @param {Map<string, string>} vectorFiles */
function renderTraceability(entries, vectorFiles) {
  const tests = witnessTests(vectorFiles);
  /** @type {Map<string, Entry[]>} */
  const byDocument = new Map();
  for (const entry of entries) {
    for (const citation of entry.doc.length > 0 ? entry.doc : ['(no document)']) {
      const list = byDocument.get(citation) ?? [];
      list.push(entry);
      byDocument.set(citation, list);
    }
  }
  const lines = [
    '# Formal specification traceability',
    '',
    BANNER,
    '',
    'Each documented sentence the model formalises, the Lean declarations that cite it, the TypeScript symbols they mirror, and the conformance suite that replays their vectors against the real code.',
    '',
    '| Document anchor | Lean declaration | Tier | TypeScript | Conformance test |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const citation of [...byDocument.keys()].sort()) {
    for (const entry of byDocument.get(citation) ?? []) {
      lines.push(
        `| ${cell(citation === '(no document)' ? citation : citationLink(citation))} | \`${shortName(entry.name)}\` | ${entry.tier ?? 'def'} | ${cell(entry.ts.map(citationLink).join(', '))} | ${cell([...(tests.get(entry.name) ?? [])].sort().map(citationLink).join(', '))} |`,
      );
    }
  }
  return `${lines.join('\n')}\n`;
}

/**
 * The ER snapshot pins, as Lean, from the latest entry of the migration journal and the
 * `drizzle-kit` snapshot it names. A unique key is a unique constraint or a unique index, as
 * `aw_er_snapshot_theorems` reads them.
 */
function renderErSnapshot() {
  /** @type {{ entries: { tag: string }[] }} */
  const journal = JSON.parse(readFileSync(path.join(MIGRATIONS_META, '_journal.json'), 'utf8'));
  const tag = journal.entries.at(-1)?.tag;
  if (tag === undefined) throw new Error('migrations/meta/_journal.json has no entries');
  const file = `${tag.slice(0, tag.indexOf('_'))}_snapshot.json`;
  /**
   * @type {{ tables: Record<string, { name: string, columns: object, foreignKeys: object,
   *   uniqueConstraints: object, indexes: Record<string, { isUnique: boolean }>,
   *   checkConstraints: object }> }}
   */
  const snapshot = JSON.parse(readFileSync(path.join(MIGRATIONS_META, file), 'utf8'));
  const tables = Object.values(snapshot.tables);
  /** @param {(table: (typeof tables)[number]) => number} count */
  const total = (count) => String(tables.reduce((sum, table) => sum + count(table), 0));
  const names = tables.map((table) => `"${table.name}"`);
  const uniques = total(
    (t) =>
      Object.keys(t.uniqueConstraints).length +
      Object.values(t.indexes).filter((index) => index.isUnique).length,
  );
  return [
    '/-! Generated by scripts/formal/generate.mjs from migrations/meta/_journal.json and',
    `migrations/meta/${file}. Do not edit; run \`pnpm formal:generate\`. -/`,
    '',
    'namespace AgentWorkspace.Er.Snapshot',
    '',
    "/-- The latest migration's `drizzle-kit` snapshot, under `migrations/meta/`. -/",
    `def file : String := "${file}"`,
    '',
    "/-- The SQL names of the snapshot's tables. -/",
    `def tableNames : List String :=\n  [${names.join(',\n    ')}]`,
    '',
    `def tableCount : Nat := ${String(tables.length)}`,
    `def columnCount : Nat := ${total((t) => Object.keys(t.columns).length)}`,
    `def foreignKeyCount : Nat := ${total((t) => Object.keys(t.foreignKeys).length)}`,
    `def uniqueCount : Nat := ${uniques}`,
    `def checkCount : Nat := ${total((t) => Object.keys(t.checkConstraints).length)}`,
    '',
    'end AgentWorkspace.Er.Snapshot',
    '',
  ].join('\n');
}

/** @param {string} directory @returns {Map<string, string>} */
function readTree(directory) {
  /** @type {Map<string, string>} */
  const tree = new Map();
  let files;
  try {
    files = listFiles(directory);
  } catch {
    return tree;
  }
  for (const file of files) {
    tree.set(path.relative(directory, file).split(path.sep).join('/'), readFileSync(file, 'utf8'));
  }
  return tree;
}

/** @param {string} text */
function normaliseNewlines(text) {
  return text.replace(/\r\n/gu, '\n');
}

/**
 * `--citations <catalogue.json>`: validate the citations of a catalogue a unit produced for its
 * own modules (`lake exe catalogue <out> <Module …>`), before they are part of the root.
 * @param {string} file
 */
function checkCitationsOnly(file) {
  /** @type {{ entries: Entry[] }} */
  const catalogue = JSON.parse(readFileSync(file, 'utf8'));
  const failures = citationFailures(catalogue.entries);
  const untraced = catalogue.entries.filter((e) => e.doc.length === 0 && e.ts.length === 0);
  for (const entry of untraced) failures.push(`${entry.name}: no citation`);
  if (failures.length > 0) {
    console.error(`citations failed:\n${failures.map((f) => `- ${f}`).join('\n')}`);
    process.exitCode = 1;
    return;
  }
  console.log(`citations: ${String(catalogue.entries.length)} entries, every citation resolves.`);
}

async function main() {
  const citationsIndex = process.argv.indexOf('--citations');
  if (citationsIndex >= 0) {
    const file = process.argv[citationsIndex + 1];
    if (file === undefined) {
      console.error('usage: node scripts/formal/generate.mjs --citations <catalogue.json>');
      process.exitCode = 2;
      return;
    }
    checkCitationsOnly(file);
    return;
  }
  const mode = process.argv.includes('--write')
    ? 'write'
    : process.argv.includes('--check')
      ? 'check'
      : null;
  if (mode === null) {
    console.error('usage: node scripts/formal/generate.mjs --write|--check [--no-lake]');
    process.exitCode = 2;
    return;
  }
  const useLake = !process.argv.includes('--no-lake');
  const erSnapshot = renderErSnapshot();
  // The model imports the pins, so they are current before `lake` builds it.
  if (mode === 'write') await writeFile(ER_SNAPSHOT_LEAN, erSnapshot);

  /** @type {string} */
  let catalogueJson;
  /** @type {Map<string, string>} */
  let vectorFiles;
  if (useLake) {
    const scratch = mkdtempSync(path.join(os.tmpdir(), 'formal-generate-'));
    try {
      runLake(['exe', 'catalogue', path.join(scratch, 'catalogue.json')]);
      runLake(['exe', 'vectors', path.join(scratch, 'vectors')]);
      catalogueJson = readFileSync(path.join(scratch, 'catalogue.json'), 'utf8');
      vectorFiles = readTree(path.join(scratch, 'vectors'));
    } finally {
      rmSync(scratch, { recursive: true, force: true });
    }
  } else {
    catalogueJson = readFileSync(CATALOGUE_JSON, 'utf8');
    vectorFiles = readTree(VECTORS_DIR);
  }

  /** @type {{ entries: Entry[] }} */
  const catalogue = JSON.parse(catalogueJson);
  const entries = catalogue.entries;
  const failures = citationFailures(entries);
  const theoremNames = new Set(entries.filter((e) => e.tier !== null).map((e) => e.name));
  for (const [relative, contents] of vectorFiles) {
    /** @type {{ vectors?: { id?: string, witnesses?: string[] }[] }} */
    const parsed = JSON.parse(contents);
    for (const vector of parsed.vectors ?? []) {
      for (const witness of vector.witnesses ?? []) {
        if (!theoremNames.has(witness)) {
          failures.push(
            `${relative} ${vector.id ?? '?'}: witness ${witness} is not a catalogued theorem`,
          );
        }
      }
    }
  }

  /** @type {Map<string, string>} */
  const outputs = new Map([
    [CATALOGUE_JSON, catalogueJson],
    [CATALOGUE_MD, renderCatalogue(entries)],
    [TRACEABILITY_MD, renderTraceability(entries, vectorFiles)],
    [ER_SNAPSHOT_LEAN, erSnapshot],
  ]);
  for (const [relative, contents] of vectorFiles) {
    outputs.set(path.join(VECTORS_DIR, ...relative.split('/')), contents);
  }

  if (mode === 'check') {
    for (const [file, expected] of outputs) {
      let actual = null;
      try {
        actual = readFileSync(file, 'utf8');
      } catch {
        // reported below
      }
      if (actual === null || normaliseNewlines(actual) !== normaliseNewlines(expected)) {
        failures.push(`${path.relative(REPOSITORY_ROOT, file)} is stale`);
      }
    }
    for (const relative of readTree(VECTORS_DIR).keys()) {
      if (!vectorFiles.has(relative)) {
        failures.push(`formal/generated/vectors/${relative} is no longer generated`);
      }
    }
  } else {
    rmSync(VECTORS_DIR, { recursive: true, force: true });
    for (const [file, contents] of outputs) {
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, contents);
    }
  }

  if (failures.length > 0) {
    console.error(`formal generate --${mode} failed:\n${failures.map((f) => `- ${f}`).join('\n')}`);
    if (mode === 'check') console.error('Run `pnpm formal:generate` and commit the result.');
    process.exitCode = 1;
    return;
  }
  console.log(
    `formal generate --${mode}: ${String(entries.length)} catalogue entries, ${String(vectorFiles.size)} vector files, every citation resolves.`,
  );
}

const invokedPath = process.argv[1];
if (
  invokedPath !== undefined &&
  pathToFileURL(path.resolve(invokedPath)).href === import.meta.url
) {
  await main();
}
