/**
 * `docs/platform-matrix.md`, rendered from what each platform target declares and what the
 * platform conformance kit observes (ADR-0133, #956).
 *
 * The counterpart of `tests/engine-matrix/renderer.ts`, for the same reason: a capability table
 * written by hand is wrong the day a target changes. The capability rows are each target's own
 * `capabilities` declaration (the value `compileForPlatform` callers and the report consult), and
 * the conformance row runs `runPlatformConformance` against that target, so a target that claims
 * more than it reports shows a `✗` rather than a tick.
 *
 * The renderer is a module so it can import the packages' TypeScript directly:
 * `tests/platform-matrix.test.ts` compares its output with the committed file, and
 * `tests/platform-matrix/run.mjs` is the `pnpm docs:generate` entry that rewrites it.
 */
import { PLATFORM_CAPABILITY_KEYS } from '@indx-workspace/contracts/platforms';
import type { PlatformCapabilityKey } from '@indx-workspace/contracts/platforms';
import { PLATFORM_TARGETS } from '@indx-workspace/platforms';
import type { PlatformTarget } from '@indx-workspace/platforms';
import { runPlatformConformance } from '@indx-workspace/platforms/testing';

/** The targets the matrix has a column for: every target the package registers. */
export const PLATFORM_MATRIX_COLUMNS: readonly PlatformTarget[] = PLATFORM_TARGETS;

const CAPABILITY_LABELS: Readonly<Record<PlatformCapabilityKey, string>> = {
  description: 'Description',
  instructions: 'Instructions',
  model: 'Model choice',
  engine: 'Agent engine choice',
  permissions: 'File, command and network permissions',
  mcpRemote: 'Remote MCP servers',
  mcpStdio: 'Local (stdio) MCP servers',
  codeTools: 'Code tools',
  openapiTools: 'OpenAPI tools',
  builtinTools: 'Built-in tools',
  skills: 'Skills',
  knowledgeFiles: 'Knowledge files',
  knowledgeUrls: 'Knowledge URLs',
  knowledgeConnectors: 'Knowledge connectors',
  subagents: 'Subagents',
  limits: 'Turn and budget limits',
};

const SUPPORT_CELLS = { native: '✓', mapped: '≈', unsupported: '-' } as const;

/**
 * The options a target needs before it compiles anything. A target with a required option has no
 * default to put in front of the kit, so the matrix supplies the same literal that target's own
 * conformance test uses.
 */
const CONFORMANCE_OPTIONS: Readonly<Record<string, unknown>> = {
  'copilot-studio': { publisherPrefix: 'acme' },
  'aws-agentcore': { region: 'us-east-1', accountId: '123456789012' },
  'gemini-enterprise': {
    projectId: 'acme-agents',
    location: 'global',
    engineId: 'acme-support-app',
    publicBaseUrl: 'https://aw.example.com',
  },
};

function conformanceCell(target: PlatformTarget): string {
  try {
    runPlatformConformance(target, CONFORMANCE_OPTIONS[target.id] ?? {});
    return '✓';
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    const reason = message.split('\n')[1]?.replace(/^- /u, '') ?? message;
    return `✗ ${reason.replaceAll('|', '\\|')}`;
  }
}

/** Render the matrix. */
export function renderPlatformMatrix(): string {
  const lines: string[] = [
    '# Platform matrix',
    '',
    'Generated by `node tests/platform-matrix/run.mjs` (and gated by `tests/platform-matrix.test.ts`).',
    "Every cell is derived: the capability rows from each target's own declaration, and the",
    'conformance row from running `@indx-workspace/platforms/testing` against that target.',
    'Do not edit this file by hand.',
    '',
    '`✓` native: the platform has the capability and the field is carried as it is.',
    '`≈` mapped: the field is translated, and the report says how.',
    '`-` unsupported: the field is dropped, and the report names the ADR-0133 D8 code.',
    '',
    'The Import row is `✓` when the target can read its own layout back into a portable project',
    '(a target without an importer shows `-`); the conformance run then checks the round trip.',
    '',
  ];

  if (PLATFORM_MATRIX_COLUMNS.length === 0) {
    lines.push('No platform targets are registered yet.', '');
    return lines.join('\n');
  }

  const ids = PLATFORM_MATRIX_COLUMNS.map((target) => target.id);
  lines.push(
    `| Capability | ${ids.join(' | ')} |`,
    `| --- | ${ids.map(() => '---').join(' | ')} |`,
  );
  for (const key of PLATFORM_CAPABILITY_KEYS) {
    const cells = PLATFORM_MATRIX_COLUMNS.map((target) => SUPPORT_CELLS[target.capabilities[key]]);
    lines.push(`| ${CAPABILITY_LABELS[key]} | ${cells.join(' | ')} |`);
  }
  lines.push(
    `| Import | ${PLATFORM_MATRIX_COLUMNS.map((target) => (target.import === undefined ? '-' : '✓')).join(' | ')} |`,
    `| Conformance | ${PLATFORM_MATRIX_COLUMNS.map(conformanceCell).join(' | ')} |`,
    `| Docs | ${PLATFORM_MATRIX_COLUMNS.map((target) => `[${target.displayName}](${target.docsUrl})`).join(' | ')} |`,
    '',
    '`aws-agentcore` is a platform id here, the Amazon Bedrock AgentCore harness an agent is',
    'published to. It is also a runtime driver id (`packages/contracts/src/runtimes.ts`), where it',
    'names the sandbox a run executes in. The two are different things that share a name.',
    '',
  );
  return lines.join('\n');
}
