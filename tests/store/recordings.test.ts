/**
 * The recordings the Try it section replays when a cap stops the live chat, and the home page's featured
 * mini chat (spec, "How Try it works"). Each is one turn of a live entry's first suggested prompt,
 * made by running the entry's real agent against the platform's scripted model, never written by
 * hand. This test is the generator and the drift check: `STORE_RECORDINGS_WRITE=1` rewrites
 * `examples/store/catalog/recordings.generated.ts` from a fresh run; otherwise a fresh run must
 * equal the committed file. Run it under `flock /tmp/store-heavy.lock`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';
import { beforeAll, describe, expect, it } from 'vitest';

import { CATALOG } from '../../examples/store/catalog/index.ts';
import type { LiveEntry } from '../../examples/store/catalog/define.ts';
import {
  judgeMoment,
  recordingFor,
  recordingSchema,
  type Recording,
} from '../../examples/store/catalog/recording.ts';
import { RECORDINGS } from '../../examples/store/catalog/recordings.generated.ts';
import { RESULT_CHARTS } from '../../examples/store/catalog/charts.generated.ts';
import { recordTurn } from './proof/record-turn.ts';
import { normalize } from './recordings/normalize.ts';
import { RECORDERS } from './recordings/index.ts';

const LANGS = ['ja', 'en'] as const;
const GENERATED = fileURLToPath(
  new URL('../../examples/store/catalog/recordings.generated.ts', import.meta.url),
);
const live = CATALOG.filter((entry): entry is LiveEntry => entry.status === 'live');

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const writing = process.env['STORE_RECORDINGS_WRITE'] === '1';
/** What the generated module must hold: a fresh recording of every live entry, formatted. */
let freshText = '';
/** The entries whose recorder failed, with why: they get no recording, and their test says so. */
const failed = new Map<string, string>();

/**
 * The recordings of an entry with result charts that kept no typed answer, as `<slug> <lang>`: their
 * replay could draw no chart, so the entry's recorder did not start its run with the schema.
 */
function untypedCharted(
  recordings: readonly Recording[],
  charts: Readonly<Record<string, readonly unknown[]>>,
): string[] {
  return recordings
    .filter((recording) => (charts[recording.slug] ?? []).length > 0)
    .filter((recording) => recording.turn.structured === undefined)
    .map((recording) => `${recording.slug} ${recording.lang}`);
}

/** The generated module: one recording per line, as JSON, so the store's line count stays small. */
function render(recordings: readonly Recording[]): string {
  return [
    '// Generated by `STORE_RECORDINGS_WRITE=1 pnpm vitest run --project tests-store tests/store/recordings.test.ts`,',
    "// which runs each live entry's real agent against the scripted model. Do not edit by hand:",
    '// tests/store/recordings.test.ts fails when this file differs from a fresh recording.',
    '',
    "import { recordingSchema, type Recording } from './recording.ts';",
    '',
    'const RECORDED: readonly string[] = [',
    ...recordings.map((recording) => `  ${JSON.stringify(JSON.stringify(recording))},`),
    '];',
    '',
    '/** One recording per live entry and language. */',
    'export const RECORDINGS: readonly Recording[] = RECORDED.map((text) =>',
    '  recordingSchema.parse(JSON.parse(text) as unknown),',
    ');',
    '',
  ].join('\n');
}

beforeAll(async () => {
  const made: Recording[] = [];
  for (const entry of live) {
    const record = RECORDERS[entry.slug];
    for (const lang of LANGS) {
      if (record === undefined || failed.has(entry.slug)) continue;
      const first = entry.demo.prompts[0];
      if (first === undefined) throw new Error(`${entry.slug} has no suggested prompt`);
      const prompt = first[lang];
      const records = entry.demo.records;
      try {
        made.push(
          normalize({
            slug: entry.slug,
            lang,
            recordedWith: 'scripted-model' as const,
            turn: recordTurn(
              prompt,
              await record({
                slug: entry.slug,
                agent: entry.demo.agent,
                lang,
                prompt,
                ja: first.ja,
                records: records === undefined ? null : path.join(ROOT, entry.source, records),
                outputSchema: entry.demo.outputSchema ?? null,
              }),
            ),
          }),
        );
      } catch (error) {
        // No recording of a run that did not happen: the entry shows "recording coming".
        failed.set(entry.slug, error instanceof Error ? error.message : String(error));
        made.splice(0, made.length, ...made.filter((recording) => recording.slug !== entry.slug));
      }
    }
  }
  const options = (await resolveConfig(GENERATED)) ?? {};
  freshText = await format(render(made), { ...options, filepath: GENERATED });
  if (writing) writeFileSync(GENERATED, freshText);
}, 600_000);

describe('the recordings of the live entries', () => {
  for (const entry of live) {
    describe(entry.slug, () => {
      for (const lang of LANGS) {
        it(`has one recording in ${lang} that shows the entry's moment`, () => {
          expect(failed.get(entry.slug) ?? null, `${entry.slug}: could not be recorded`).toBeNull();
          const committed = RECORDINGS.filter(
            (recording) => recording.slug === entry.slug && recording.lang === lang,
          );
          expect(committed, `${entry.slug} ${lang}: one recording`).toHaveLength(1);
          const recording = recordingFor(RECORDINGS, entry.slug, lang);
          expect(recording, `${entry.slug} ${lang}`).not.toBeNull();
          if (recording === null) return;
          expect(recordingSchema.safeParse(recording).success).toBe(true);
          expect(recording.recordedWith).toBe('scripted-model');
          expect(recording.turn.prompt).toBe(entry.demo.prompts[0]?.[lang]);
          const check = entry.demo.check;
          expect(
            check,
            `${entry.slug} has no demo.check, so its moment cannot be judged`,
          ).toBeDefined();
          if (check === undefined) return;
          expect(judgeMoment(recording.turn, check)).toEqual({ pass: true });
        });
      }
    });
  }

  // Read after the optional write, so the write run compares the file it just made and still runs.
  it('equals a fresh recording of every live entry (drift)', () => {
    expect(readFileSync(GENERATED, 'utf8')).toBe(freshText);
  });

  it("keeps the typed answer of every charted entry's recording, for its replay's charts", () => {
    expect(untypedCharted(RECORDINGS, RESULT_CHARTS)).toEqual([]);
    const turn = { prompt: 'q', steps: [], stopReason: null };
    const recording: Recording = { slug: 'x', lang: 'ja', recordedWith: 'scripted-model', turn };
    expect(untypedCharted([recording], { x: [{}] })).toEqual(['x ja']);
    expect(
      untypedCharted([{ ...recording, turn: { ...turn, structured: {} } }], { x: [{}] }),
    ).toEqual([]);
    expect(untypedCharted([recording], {})).toEqual([]);
  });

  it('has a recorder for every live entry and none for another', () => {
    expect(Object.keys(RECORDERS).sort()).toEqual(live.map((entry) => entry.slug).sort());
  });
});
