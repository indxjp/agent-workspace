import { MeResponseSchema, type MeResponse } from '@indx-workspace/contracts/team';
import { createServer, type Server } from 'node:http';
import path from 'node:path';
import { Readable } from 'node:stream';
import createClient from 'openapi-fetch';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { document, repoRoot } from './openapi.test-support.js';

const me: MeResponse = {
  principalId: 'principal-1',
  kind: 'membership',
  role: 'owner',
  workspaceId: 'workspace-1',
  userId: 'user-1',
  label: 'Ada',
  features: ['chat'],
};

let server: Server;

let baseUrl: string;

const seen: {
  method: string | undefined;
  url: string | undefined;
  authorization: string | undefined;
}[] = [];

beforeAll(async () => {
  server = createServer((request, response) => {
    seen.push({
      method: request.method,
      url: request.url,
      authorization: request.headers.authorization,
    });
    if (request.method === 'GET' && request.url === '/api/me') {
      response.writeHead(200, { 'content-type': 'application/json' });
      response.end(JSON.stringify(me));
      return;
    }
    response.writeHead(404, { 'content-type': 'application/json' });
    response.end(JSON.stringify({ error: { code: 'not_found', message: 'Not found.' } }));
  });
  await new Promise<void>((resolve) => server.listen(0, '127.0.0.1', resolve));
  const address = server.address();
  if (address === null || typeof address === 'string')
    throw new Error('The test server has no TCP address.');
  baseUrl = `http://127.0.0.1:${String(address.port)}`;
});

afterAll(async () => {
  await new Promise<void>((resolve) => server.close(() => resolve()));
});

/** openapi-typescript's output for the document, type-checked together with `usage`. */
async function typeCheckAgainstGeneratedTypes(usage: string): Promise<readonly string[]> {
  const generated = astToString(await openapiTS(Readable.from([JSON.stringify(document)])));
  const dir = path.join(repoRoot, 'tests', 'docs', '.generated-client');
  const files = new Map([
    [path.join(dir, 'api.ts'), generated],
    [path.join(dir, 'usage.ts'), usage],
  ]);
  const options: ts.CompilerOptions = {
    strict: true,
    noEmit: true,
    target: ts.ScriptTarget.ES2023,
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    lib: ['lib.es2023.d.ts', 'lib.dom.d.ts'],
    types: [],
    skipLibCheck: true,
  };
  const host = ts.createCompilerHost(options);
  const readFileOnDisk = host.readFile.bind(host);
  const fileExistsOnDisk = host.fileExists.bind(host);
  const getSourceFileOnDisk = host.getSourceFile.bind(host);
  const normalise = (fileName: string): string => path.resolve(fileName);
  host.fileExists = (fileName) => files.has(normalise(fileName)) || fileExistsOnDisk(fileName);
  // The generated files exist only in memory, so their directory does too.
  host.directoryExists = (directory) =>
    normalise(directory) === dir || ts.sys.directoryExists(directory);
  host.readFile = (fileName) => files.get(normalise(fileName)) ?? readFileOnDisk(fileName);
  host.getSourceFile = (fileName, language, onError, shouldCreate) => {
    const text = files.get(normalise(fileName));
    return text === undefined
      ? getSourceFileOnDisk(fileName, language, onError, shouldCreate)
      : ts.createSourceFile(fileName, text, language);
  };
  const program = ts.createProgram([path.join(dir, 'usage.ts')], options, host);
  return ts
    .getPreEmitDiagnostics(program)
    .map((diagnostic) => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'));
}
describe('a client generated by an off-the-shelf generator', () => {
  it(
    'generates types in which GET /api/me answers the MeResponse shape',
    generatesTypesWhichGETApiMeAnswers,
    30_000,
  );

  it('calls GET /api/me successfully', callsGETApiMeSuccessfully);
});

async function generatesTypesWhichGETApiMeAnswers() {
  const usage = [
    "import createClient from 'openapi-fetch';",
    "import type { paths } from './api.js';",
    "const client = createClient<paths>({ baseUrl: 'http://localhost:3000' });",
    'export async function workspaceOf(): Promise<string | undefined> {',
    "  const { data } = await client.GET('/api/me');",
    '  return data?.workspaceId;',
    '}',
  ].join('\n');
  expect(await typeCheckAgainstGeneratedTypes(usage)).toEqual([]);

  const wrong = usage.replace("'/api/me'", "'/api/not-a-route'");
  expect((await typeCheckAgainstGeneratedTypes(wrong)).length).toBeGreaterThan(0);
  // Two TypeScript programs: ~3 s on a 2-vCPU CI runner, too close to the 5 s default.
}

async function callsGETApiMeSuccessfully() {
  const client = createClient<{
    '/api/me': {
      get: { responses: { 200: { content: { 'application/json': MeResponse } } } };
    };
  }>({ baseUrl, headers: { authorization: 'Bearer ak_live_test' } });
  const { data, error, response } = await client.GET('/api/me');
  expect(error).toBeUndefined();
  expect(response.status).toBe(200);
  expect(MeResponseSchema.parse(data)).toEqual(me);

  // Tie the call to the emitted document: its 200 names the MeResponse component, which is the
  // contract schema converted, and the answer carries exactly what that component declares.
  const paths = document['paths'] as Record<string, Record<string, Record<string, unknown>>>;
  const responses = paths['/api/me']?.['get']?.['responses'] as Record<
    string,
    { content?: Record<string, { schema?: { $ref?: string } }> }
  >;
  const pointer = responses['200']?.content?.['application/json']?.schema?.$ref;
  expect(pointer).toBe('#/components/schemas/MeResponse');
  const schemas = (document['components'] as Record<string, Record<string, unknown>>)['schemas'];
  const component = schemas?.['MeResponse'] as {
    required?: string[];
    properties?: Record<string, unknown>;
  };
  const converted: Record<string, unknown> = {
    ...MeResponseSchema.toJSONSchema({
      target: 'draft-2020-12',
      io: 'output',
      unrepresentable: 'any',
    }),
  };
  delete converted['$schema'];
  expect(component).toEqual(converted);
  for (const field of component.required ?? []) expect(data).toHaveProperty(field);
  const declared = Object.keys(component.properties ?? {});
  expect(Object.keys(data ?? {}).filter((field) => !declared.includes(field))).toEqual([]);
  expect(seen.at(-1)).toEqual({
    method: 'GET',
    url: '/api/me',
    authorization: 'Bearer ak_live_test',
  });
}
