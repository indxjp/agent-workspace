import prettier from 'prettier';

/** @typedef {{basis: string, values?: string[], unverified?: boolean, outOfScope?: boolean}} DriverResult */
/** @typedef {{drivers: string[], rows: string[][], legend: string}} A10 */

export const NO_SCENARIO_ROWS = new Set([
  'Isolation',
  'Custom image',
  'Start latency',
  'Needs Docker socket',
  'Runs on Fargate',
]);

/**
 * How each driver picks the image a run starts in (ENG-07, ADR-0073). Not an A.10 row: it is a
 * property of the driver's construction rather than a capability an A.12 scenario measures.
 */
const ENGINE_IMAGES_NOTE = [
  '## Engine images',
  '',
  'A runtime image carries exactly one engine adapter, and a deployment configures one image per engine it offers ([ADR-0073](adr/0073-one-runtime-image-per-engine.md)).',
  '',
  "- `docker`, `k8s` and `cloudrun` take the deployment's `engine → image` map and start each run in the image for the run's engine. An engine with no image is refused as `engine_not_installed` before a container, pod or service is created.",
  '- `local` and `sbx-rt` take no image: they run the runner in-process and load whatever adapters are installed in the workspace.',
  "- `aca-sess` serves **one engine per session pool**. A pool is provisioned with one container image and its management API cannot ask for another, so the driver takes the pool's engine (`ACA_SESSION_POOL_ENGINE`) and refuses any other before an allocation is made. A deployment offering two engines over ACA provisions two pools and two runner managers. This is a per-driver gap, not a design choice.",
  '- `gke-as`, `agentcore` and `ecs` have no driver yet; each takes the map when it lands.',
  '',
].join('\n');

/** @param {string} spec @returns {A10} */
export function parseA10(spec) {
  const block = spec.match(/## A\.10 Comparison matrix[\s\S]*?```text\r?\n([\s\S]*?)```/u)?.[1];
  if (!block) throw new Error('spec A.10 text block was not found');
  const lines = block.trimEnd().split(/\r?\n/u);
  const firstLine = lines[0];
  if (!firstLine) throw new Error('spec A.10 driver header was not found');
  const drivers = firstLine.trim().split(/\s{2,}/u);
  const rows = lines.slice(1, -2).map((line) => line.trim().split(/\s{2,}/u));
  if (drivers.length !== 9 || rows.length !== 10 || rows.some((row) => row.length !== 10)) {
    throw new Error(
      `A.10 shape changed: ${String(rows.length)} rows, ${String(drivers.length)} drivers`,
    );
  }
  const legend = lines.find((line) => line.includes('native') && line.includes('unsupported'));
  if (!legend) throw new Error('spec A.10 legend was not found');
  return { drivers, rows, legend };
}

/** @param {string} spec @param {Record<string, DriverResult>} results */
export async function renderDriverMatrix(spec, results) {
  const { drivers, rows, legend } = parseA10(spec);
  for (const driver of drivers) {
    const result = results[driver];
    if (!result || typeof result.basis !== 'string') {
      throw new Error(`${driver} has no backing result`);
    }
    if (
      !result.unverified &&
      !result.outOfScope &&
      (!Array.isArray(result.values) || result.values.length !== rows.length)
    ) {
      throw new Error(`${driver} has no value for every A.10 capability row`);
    }
  }

  const rendered = rows.map((row, rowIndex) => {
    const name = row[0];
    if (!name) throw new Error(`A.10 row ${String(rowIndex + 1)} has no capability name`);
    return [
      name,
      ...drivers.map((driver) => {
        const result = results[driver];
        if (!result) throw new Error(`${driver} has no backing result`);
        if (NO_SCENARIO_ROWS.has(name)) return 'n/d';
        if (result.outOfScope) return 'n/d';
        if (result.unverified) return '?';
        return result.values?.[rowIndex] ?? '?';
      }),
    ];
  });
  const header = ['Capability', ...drivers];
  const table = [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rendered.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
  const basis = drivers
    .map((driver) => {
      const result = results[driver];
      if (!result) throw new Error(`${driver} has no backing result`);
      return `- \`${driver}\`: ${result.basis}.`;
    })
    .join('\n');
  const output = `# Runtime driver matrix\n\nGenerated by \`node tests/driver-matrix/run.mjs\` from spec A.10's ${String(rows.length)} capability rows, its ${String(drivers.length)} driver columns, and the checked-in result record. \`?\` means a scenario exists but was not verified in this build. \`n/d\` means no A.12 scenario can derive the cell or the driver is outside the 0.1.0 scope.\n\n${table}\n\nLegend:\n\n\`\`\`text\n${legend}\n\`\`\`\n\n? not verified in this build\nn/d not derivable from A.12 or out of 0.1.0 scope\n\n## Evidence basis\n\n${basis}\n\n${ENGINE_IMAGES_NOTE}`;
  return prettier.format(output, { parser: 'markdown' });
}
