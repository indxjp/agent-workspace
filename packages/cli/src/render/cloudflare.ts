/**
 * The Workers a `cloud: cloudflare` profile renders under `deploy/cloudflare/` (ADR-0125, ADR-0127,
 * ADR-0129).
 *
 * Four Workers, each a Wrangler configuration and the module it runs:
 *
 * - the platform Worker (`wrangler.jsonc`, `retention-worker.mjs`): a Cron Trigger that calls the
 *   control plane's `GET /api/cron/retention` with `Authorization: Bearer $CRON_SECRET`, the route
 *   Vercel Cron already uses. Vendor facts, checked 2026-10-08: a Cron Trigger is a five-field
 *   expression in UTC that invokes the Worker's `scheduled` handler
 *   (https://developers.cloudflare.com/workers/configuration/cron-triggers/); `triggers.crons`,
 *   `main` and `compatibility_date` are Wrangler configuration keys, and the file may be
 *   `wrangler.jsonc` (https://developers.cloudflare.com/workers/wrangler/configuration/).
 * - the control plane Worker (`control-plane.wrangler.jsonc`, `control-plane-worker.mjs`): a
 *   Durable Object that runs the `web` image as a Cloudflare Container and proxies every request to
 *   it (ADR-0120 clause 7, ADR-0127).
 * - the gateway Worker (`gateway.wrangler.jsonc`, `gateway-worker.mjs`) and the runner manager
 *   Worker (`manager.wrangler.jsonc`, `manager-worker.mjs`): the same Container Worker for the
 *   `gateway` and `runner` images (ADR-0129).
 *
 * The configurations carry no name, account id or secret: `deploy` passes `--name`, and the
 * account through the child's environment, and the Workers' secrets are uploaded, never rendered.
 * For a container Worker, `deploy` also stamps the Worker name into the temporary copy it hands to
 * `wrangler deploy` and `wrangler secret bulk`, because wrangler 4.147 requires a top-level `name`
 * next to `containers`.
 * The frontend Worker is not rendered: its assets directory is the project's own `web/` build, known
 * only when `deploy` runs, so `cloudflareFrontendConfiguration` builds its configuration then.
 */
import { containerWorkerModule } from './cloudflare-container-module.ts';
import type { DeploymentImages } from '../deployment.ts';
import type { DeploymentProfile } from '../profile.ts';

/** The route `apps/web/app/api/cron/retention` serves, authenticated by `CRON_SECRET`. */
export const CLOUDFLARE_RETENTION_CRON_PATH = '/api/cron/retention';

/** The route `apps/web/app/api/cron/triggers` serves: the schedule pass (ADR-0144 D5). */
const CLOUDFLARE_TRIGGERS_CRON_PATH = '/api/cron/triggers';

/** Daily, matching the Vercel target (ADR-0120 clause 7). */
const RETENTION_SCHEDULE = '0 3 * * *';

const COMPATIBILITY_DATE = '2026-10-01';

export const CLOUDFLARE_CONFIG_FILE = 'wrangler.jsonc';
export const CLOUDFLARE_WORKER_FILE = 'retention-worker.mjs';
export const CLOUDFLARE_CONTROL_PLANE_CONFIG_FILE = 'control-plane.wrangler.jsonc';
const CONTROL_PLANE_WORKER_FILE = 'control-plane-worker.mjs';
export const CLOUDFLARE_GATEWAY_CONFIG_FILE = 'gateway.wrangler.jsonc';
const GATEWAY_WORKER_FILE = 'gateway-worker.mjs';
export const CLOUDFLARE_MANAGER_CONFIG_FILE = 'manager.wrangler.jsonc';
const MANAGER_WORKER_FILE = 'manager-worker.mjs';

/**
 * How long a container stays up after its last request, in seconds. The Worker hands it to the
 * container as `AW_CONTAINER_IDLE_STOP_SECONDS`, and web derives its longest run from that variable
 * (`hostRunLimitMs`), so a run cannot be promised more time than the container is kept.
 */
const CONTAINER_IDLE_STOP_SECONDS = 900;
const CONTROL_PLANE_PORT = 3000;
const GATEWAY_PORT = 4000;
const MANAGER_PORT = 8090;

/**
 * The secrets without which the web server cannot start or sign anyone in (`DATABASE_URL`, the
 * master key, the session key and the bootstrap administrator). The Worker answers 503 and starts
 * no container until every one of them is a non-empty binding.
 */
const CONTROL_PLANE_REQUIRED_SECRETS = [
  'DATABASE_URL',
  'MASTER_ENCRYPTION_KEY',
  'SESSION_SECRET',
  'BOOTSTRAP_ADMIN',
  'BOOTSTRAP_ADMIN_PASSWORD',
] as const;

/** What the gateway cannot serve a token or decrypt a provider key without. */
const GATEWAY_REQUIRED_SECRETS = [
  'DATABASE_URL',
  'MASTER_ENCRYPTION_KEY',
  'GATEWAY_TOKEN_SECRET',
] as const;

/**
 * What the manager cannot authenticate its caller, pick a driver or reach the gateway without, and
 * what its driver cannot start without: E2B's provider name, or the sandbox bridge's address.
 */
const managerRequiredSecrets = (profile: DeploymentProfile) => [
  'RUNNER_MANAGER_TOKEN',
  'RUNTIME_DRIVER',
  'GATEWAY_PUBLIC_URL',
  profile.runtime.default === 'external' ? 'EXTERNAL_PROVIDER' : 'CLOUDFLARE_SANDBOX_BRIDGE_URL',
];

/** The `web` image's start command without the `migrate` and `seed` steps `CMD` chains before it. */
const CONTROL_PLANE_ENTRYPOINT = [
  'node',
  '/srv/apps/web/node_modules/next/dist/bin/next',
  'start',
] as const;

const WORKER_MODULE = `// Generated by agent-workspace. Calls the control plane's session retention and schedule trigger routes on a Cron Trigger.
export default {
  async scheduled(_controller, env) {
    if (!env.CONTROL_PLANE_URL) throw new Error('CONTROL_PLANE_URL is not set');
    if (!env.CRON_SECRET) throw new Error('CRON_SECRET is not set');
    const base = env.CONTROL_PLANE_URL.replace(/\\/+$/, '');
    const failures = [];
    for (const path of ['${CLOUDFLARE_RETENTION_CRON_PATH}', '${CLOUDFLARE_TRIGGERS_CRON_PATH}']) {
      const response = await globalThis.fetch(base + path, {
        headers: { authorization: 'Bearer ' + env.CRON_SECRET },
      });
      if (!response.ok) failures.push('The ' + path + ' route answered ' + response.status);
    }
    if (failures.length > 0) throw new Error(failures.join('; '));
  },
};
`;

const CONTROL_PLANE_MODULE = containerWorkerModule({
  idleStopSeconds: CONTAINER_IDLE_STOP_SECONDS,
  runs: "the control plane's web image",
  service: 'control plane',
  className: 'Web',
  binding: 'WEB',
  objectName: 'control-plane',
  port: CONTROL_PLANE_PORT,
  entrypoint: CONTROL_PLANE_ENTRYPOINT,
  entrypointNote:
    'Starts the server only: a cold start never migrates (the deploy runs the migrations once).',
  requiredSecrets: CONTROL_PLANE_REQUIRED_SECRETS,
});

// The gateway and manager images' `CMD` has no migrate step; the start command is still passed
// explicitly so a Worker never depends on the image's default staying what it is.
const GATEWAY_MODULE = containerWorkerModule({
  idleStopSeconds: CONTAINER_IDLE_STOP_SECONDS,
  runs: 'the model gateway image',
  service: 'model gateway',
  className: 'Gateway',
  binding: 'GATEWAY',
  objectName: 'gateway',
  port: GATEWAY_PORT,
  entrypoint: ['node', 'packages/gateway/dist/index.js'],
  entrypointNote: "The image's own start command, from its working directory /workspace.",
  requiredSecrets: GATEWAY_REQUIRED_SECRETS,
});

const managerModule = (profile: DeploymentProfile) =>
  containerWorkerModule({
    idleStopSeconds: CONTAINER_IDLE_STOP_SECONDS,
    runs: 'the runner manager image',
    service: 'runner manager',
    className: 'Manager',
    binding: 'MANAGER',
    objectName: 'manager',
    port: MANAGER_PORT,
    entrypoint: ['node', 'dist/manager-start.js'],
    entrypointNote: "The image's own start command, from its working directory /srv/apps/runner.",
    requiredSecrets: managerRequiredSecrets(profile),
  });

export interface CloudflareArtefact {
  /** The directory under `deploy/` the files are written in. */
  readonly directory: string;
  readonly files: readonly { readonly fileName: string; readonly contents: string }[];
}

function containerWorkerConfiguration(
  main: string,
  className: string,
  binding: string,
  image: string,
) {
  return {
    main,
    compatibility_date: COMPATIBILITY_DATE,
    workers_dev: true,
    containers: [{ class_name: className, image, max_instances: 1, instance_type: 'standard-1' }],
    durable_objects: { bindings: [{ name: binding, class_name: className }] },
    migrations: [{ tag: 'v1', new_sqlite_classes: [className] }],
  };
}

/**
 * The frontend Worker's configuration: the project's built `web/` output served as static assets
 * with single-page-application fallback, and the project's own build run first (its environment
 * carries `VITE_AW_BASE_URL`). Vendor facts, checked 2026-10-08: `assets.directory` and
 * `assets.not_found_handling: "single-page-application"` serve a static site from a Worker with no
 * script, and `build.command` and `build.cwd` run a command before `wrangler deploy`
 * (https://developers.cloudflare.com/workers/static-assets/,
 * https://developers.cloudflare.com/workers/wrangler/custom-builds/).
 */
export function cloudflareFrontendConfiguration(
  frontendDirectory: string,
  outputDirectory: string,
) {
  return {
    compatibility_date: COMPATIBILITY_DATE,
    workers_dev: true,
    build: { command: 'npm run build', cwd: frontendDirectory },
    assets: { directory: outputDirectory, not_found_handling: 'single-page-application' },
  };
}

/** Render the platform, control plane, gateway and manager Workers, or `null` when the cloud is not `cloudflare`. */
export function renderCloudflareProject(
  profile: DeploymentProfile,
  images: DeploymentImages,
): CloudflareArtefact | null {
  if (profile.cloud !== 'cloudflare') return null;
  const configuration = {
    main: CLOUDFLARE_WORKER_FILE,
    compatibility_date: COMPATIBILITY_DATE,
    workers_dev: false,
    triggers: { crons: [RETENTION_SCHEDULE] },
  };
  const json = (value: unknown) => JSON.stringify(value, null, 2) + '\n';
  return {
    directory: 'cloudflare',
    files: [
      { fileName: CLOUDFLARE_CONFIG_FILE, contents: json(configuration) },
      { fileName: CLOUDFLARE_WORKER_FILE, contents: WORKER_MODULE },
      {
        fileName: CLOUDFLARE_CONTROL_PLANE_CONFIG_FILE,
        contents: json(
          containerWorkerConfiguration(CONTROL_PLANE_WORKER_FILE, 'Web', 'WEB', images.web),
        ),
      },
      { fileName: CONTROL_PLANE_WORKER_FILE, contents: CONTROL_PLANE_MODULE },
      {
        fileName: CLOUDFLARE_GATEWAY_CONFIG_FILE,
        contents: json(
          containerWorkerConfiguration(GATEWAY_WORKER_FILE, 'Gateway', 'GATEWAY', images.gateway),
        ),
      },
      { fileName: GATEWAY_WORKER_FILE, contents: GATEWAY_MODULE },
      {
        fileName: CLOUDFLARE_MANAGER_CONFIG_FILE,
        contents: json(
          containerWorkerConfiguration(MANAGER_WORKER_FILE, 'Manager', 'MANAGER', images.runner),
        ),
      },
      { fileName: MANAGER_WORKER_FILE, contents: managerModule(profile) },
    ],
  };
}
