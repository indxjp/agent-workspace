interface ContainerWorker {
  /** What the Worker runs, as the generated header says it: "the control plane's web image". */
  readonly runs: string;
  /** The service as the Worker's messages name it: "control plane" in "The control plane is starting". */
  readonly service: string;
  readonly className: string;
  readonly binding: string;
  /** The Durable Object every request is routed to: one object, so one container. */
  readonly objectName: string;
  readonly port: number;
  readonly entrypoint: readonly string[];
  /** Said above the entry point in the generated module. */
  readonly entrypointNote: string;
  readonly requiredSecrets: readonly string[];
}

const quoted = (parts: readonly string[]) => parts.map((part) => `'${part}'`).join(', ');

/** The array on one line when it fits the repository's 100-column format, else one name a line. */
function requiredSecretsDeclaration(names: readonly string[]): string {
  const line = `const REQUIRED_SECRETS = [${quoted(names)}];`;
  return line.length <= 100
    ? line
    : `const REQUIRED_SECRETS = [\n${names.map((name) => `  '${name}',\n`).join('')}];`;
}

// Cloudflare Containers, checked 2026-10-08: `ctx.container.start({ entrypoint, env,
// enableInternet })` boots the container and returns before it is ready (`enableInternet` is passed
// as `true` because the control plane reaches its database, R2 and the model providers, the gateway
// the providers and the manager its sandbox provider, and a server that cannot connect out hangs in
// its boot rather than failing); `getTcpPort(port).fetch` reaches it, over plain HTTP only: a
// request URL with `https:` throws, so a forward rewrites it to `http:` as @cloudflare/containers
// 0.3.7 does; `monitor()` settles when it exits, and rejects with the exit code when it exits
// non-zero; `setInactivityTimeout(ms)` keeps it up for that long after the Durable
// Object goes inactive; `destroy()` stops it and resolves once it has stopped; an update to `env`
// is read on the next start, so a rotated secret reaches a running container only through a
// restart (https://developers.cloudflare.com/durable-objects/api/container/,
// https://developers.cloudflare.com/containers/examples/env-vars-and-secrets/,
// https://developers.cloudflare.com/containers/platform-details/architecture/).
function containerWorkerModule(worker: ContainerWorker): string {
  return `// Generated by agent-workspace. Runs ${worker.runs} as a Cloudflare Container.
const PORT = ${String(worker.port)};
const IDLE_STOP_SECONDS = ${String(CONTAINER_IDLE_STOP_SECONDS)};
// ${worker.entrypointNote}
const ENTRYPOINT = [${quoted(worker.entrypoint)}];
const READY_DEADLINE_MS = 60000;
const PROBE_TIMEOUT_MS = 5000;
const READY_DELAY_MS = 500;
// The ${worker.service} cannot start without these; until \`deploy\` has put them all, nothing starts.
${requiredSecretsDeclaration(worker.requiredSecrets)}
const ENV_HASH_KEY = 'container-env-sha256';

function containerEnvironment(env) {
  const forwarded = {};
  for (const [name, value] of Object.entries(env)) {
    if (typeof value === 'string') forwarded[name] = value;
  }
  forwarded.AW_CONTAINER_IDLE_STOP_SECONDS = String(IDLE_STOP_SECONDS);
  return forwarded;
}

// A SHA-256 over the environment the container starts with: a different value means a rotation.
async function environmentHash(environment) {
  const entries = Object.entries(environment).sort(([a], [b]) => (a < b ? -1 : 1));
  const digest = await globalThis.crypto.subtle.digest(
    'SHA-256',
    new globalThis.TextEncoder().encode(JSON.stringify(entries)),
  );
  return Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, '0')).join('');
}

// A hung server never answers a probe: each one is bounded so the wait ends at the deadline.
function within(promise, ms) {
  let timer;
  const expired = new Promise((_resolve, reject) => {
    timer = globalThis.setTimeout(() => reject(new Error('probe timed out')), ms);
  });
  return Promise.race([promise, expired]).finally(() => globalThis.clearTimeout(timer));
}

// A failure whose message is safe to return in the 503 body: it names the state, never a secret.
class NotReady extends Error {}

// The answer to a throw: the step that failed and the runtime's own message, never an environment
// value. A failed forward is a bad gateway; any other step is the Worker's own fault.
function failure(step, error) {
  globalThis.console.error('${worker.service} Worker failed at ' + step, error);
  const reason = error instanceof Error ? error.name + ': ' + error.message : String(error);
  const body = { error: { code: 'worker_exception', step, message: reason.slice(0, 200) } };
  return globalThis.Response.json(body, { status: step === 'forward' ? 502 : 500 });
}

export class ${worker.className} {
  constructor(ctx, env) {
    this.ctx = ctx;
    this.env = env;
    this.listening = null;
    this.exited = null;
    this.generation = 0;
  }

  // Remembers how this start's container ended, so a crash is told apart from a slow start. A
  // container stopped by a rotation reports under an older generation and is ignored.
  watch(container) {
    this.generation += 1;
    const generation = this.generation;
    this.exited = null;
    const record = (detail) => {
      if (generation === this.generation) this.exited = detail;
    };
    container.monitor().then(
      () => record('stopped'),
      (error) => {
        globalThis.console.error('${worker.service} container exited', error);
        record(String(error instanceof Error ? error.message : error).slice(0, 200));
      },
    );
  }

  async untilListening(port) {
    const deadline = Date.now() + READY_DEADLINE_MS;
    while (Date.now() < deadline) {
      if (this.exited !== null) {
        throw new NotReady('container exited (' + this.exited + ')');
      }
      try {
        await within(port.fetch('http://container/', { redirect: 'manual' }), PROBE_TIMEOUT_MS);
        return;
      } catch {
        await new Promise((resolve) => globalThis.setTimeout(resolve, READY_DELAY_MS));
      }
    }
    const seconds = READY_DEADLINE_MS / 1000;
    throw new NotReady('did not answer on port ' + PORT + ' within ' + seconds + ' s');
  }

  // Null once the container listens; otherwise the 503 that says why it does not yet.
  async ready(container, port, environment) {
    try {
      // One request at a time decides whether to stop and start, so a rotation restarts once.
      await this.ctx.blockConcurrencyWhile(async () => {
        const hash = await environmentHash(environment);
        if (container.running && (await this.ctx.storage.get(ENV_HASH_KEY)) !== hash) {
          await container.destroy();
        }
        if (!container.running) {
          container.start({ entrypoint: ENTRYPOINT, env: environment, enableInternet: true });
          await this.ctx.storage.put(ENV_HASH_KEY, hash);
          this.watch(container);
          this.listening = null;
        }
      });
      this.listening ??= this.untilListening(port);
      await container.setInactivityTimeout(IDLE_STOP_SECONDS * 1000);
      await this.listening;
      return null;
    } catch (error) {
      this.listening = null;
      globalThis.console.error('${worker.service} container is not ready', error);
      const state = error instanceof NotReady ? error.message : 'is starting';
      const body = 'The ${worker.service} ' + state;
      return new globalThis.Response(body, { status: 503, headers: { 'retry-after': '5' } });
    }
  }

  // Nothing thrown here may escape: an uncaught exception is Cloudflare's own HTML 500 (error 1101),
  // which names neither the step nor the cause.
  async fetch(request) {
    let step = 'env';
    try {
      const environment = containerEnvironment(this.env);
      if (REQUIRED_SECRETS.some((name) => (environment[name] ?? '').trim() === '')) {
        return new globalThis.Response('The ${worker.service} is not configured yet', {
          status: 503,
          headers: { 'retry-after': '30' },
        });
      }
      step = 'container-binding';
      const container = this.ctx.container;
      if (!container) throw new Error('Containers are not enabled for the ${worker.className} class');
      const port = container.getTcpPort(PORT);
      const notReady = await this.ready(container, port, environment);
      if (notReady !== null) return notReady;
      step = 'forward';
      return await port.fetch(request.url.replace(/^https:/u, 'http:'), request);
    } catch (error) {
      return failure(step, error);
    }
  }
}

export default {
  async fetch(request, env) {
    let step = 'durable-object-binding';
    try {
      const namespace = env.${worker.binding};
      if (!namespace) throw new Error('The ${worker.binding} binding is missing');
      const object = namespace.get(namespace.idFromName('${worker.objectName}'));
      step = 'durable-object';
      return await object.fetch(request);
    } catch (error) {
      return failure(step, error);
    }
  },
};
`;
}

