import { readFile, symlink } from 'node:fs/promises';
import { mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, describe, expect, it, vi } from 'vitest';

const startMocks = vi.hoisted(() => ({
  runStartCommand: vi.fn(() => Promise.resolve()),
}));

vi.mock('./start.js', () => startMocks);

const stopMocks = vi.hoisted(() => ({
  runStopCommand: vi.fn(() => Promise.resolve()),
}));

vi.mock('./stop.ts', () => stopMocks);

const renderMocks = vi.hoisted(() => ({
  runRenderCommand: vi.fn(() => Promise.resolve([])),
}));

vi.mock('./render.ts', () => renderMocks);

const deployMocks = vi.hoisted(() => ({
  DEPLOY_CHANGES_PENDING: 2,
  runDeployCommand: vi.fn(() => Promise.resolve({ changes: false, applied: false })),
}));

vi.mock('./deploy/command.ts', () => deployMocks);
const doctorMocks = vi.hoisted(() => ({
  runDoctorCommand: vi.fn(() => Promise.resolve()),
}));

vi.mock('./doctor/index.ts', () => doctorMocks);

const originalArgv = [...process.argv];
const created: string[] = [];

afterEach(async () => {
  process.argv.splice(0, process.argv.length, ...originalArgv);
  startMocks.runStartCommand.mockClear();
  stopMocks.runStopCommand.mockClear();
  renderMocks.runRenderCommand.mockClear();
  deployMocks.runDeployCommand.mockClear();
  doctorMocks.runDoctorCommand.mockClear();
  vi.resetModules();
  await Promise.all(created.splice(0).map((entry) => rm(entry, { recursive: true })));
});

describe('@indx-workspace/cli', () => {
  it('is named what it is published as', async () => {
    const { PACKAGE_NAME } = await import('./index.js');
    const manifest = JSON.parse(
      await readFile(new URL('../package.json', import.meta.url), 'utf8'),
    ) as { name: string };
    expect(PACKAGE_NAME).toBe(manifest.name);
  });

  it('prints its usage and exits 0 for --help', async () => {
    const { HELP_TEXT, runCli } = await import('./index.js');
    const stdout = vi.spyOn(process.stdout, 'write').mockReturnValue(true);
    try {
      await runCli(['--help']);
      expect(stdout).toHaveBeenCalledWith(HELP_TEXT);
    } finally {
      stdout.mockRestore();
    }
    expect(HELP_TEXT).toContain('Usage: agent-workspace start|stop|validate|render|doctor|deploy');
    // `stop` takes no directory, so the usage line advertises none; each verb's line has its own.
    expect(HELP_TEXT.split('\n')[0]).toBe(
      'Usage: agent-workspace start|stop|validate|render|doctor|deploy',
    );
    expect(HELP_TEXT).toContain('stop [--volumes]');
    expect(HELP_TEXT).toContain('render [dir] [--check]');
    expect(HELP_TEXT).toContain(
      'deploy [dir] [--yes] [--target helm|terraform|vercel|cloudflare] [--infra <dir>]',
    );
    // #496: without --cloud, create writes a kind: Project directory, which aw dev runs.
    expect(HELP_TEXT).toContain('aw dev');
    expect(HELP_TEXT).toContain('npm create @indx-workspace <directory> -- --cloud local');
    expect(HELP_TEXT).not.toContain('A project is generated by create-agent-workspace');
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  // Issue #416: `agent-workspace --version` was "Unknown command".
  it('prints the CLI and contracts versions for --version, the same way aw does', async () => {
    const { runCli } = await import('./index.js');
    const { CLI_VERSION } = await import('./version.js');
    const { CONTRACTS_VERSION } = await import('@indx-workspace/contracts');
    const manifest = JSON.parse(
      await readFile(new URL('../package.json', import.meta.url), 'utf8'),
    ) as { version: string };
    expect(CLI_VERSION).toBe(manifest.version);
    const stdout = vi.spyOn(process.stdout, 'write').mockReturnValue(true);
    try {
      await runCli(['--version']);
      expect(stdout).toHaveBeenCalledWith(
        `agent-workspace ${manifest.version} (contracts ${CONTRACTS_VERSION})
`,
      );
    } finally {
      stdout.mockRestore();
    }
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  it('does not start merely because an importer has start in argv[2]', async () => {
    process.argv.splice(
      0,
      process.argv.length,
      process.execPath,
      fileURLToPath(import.meta.url),
      'start',
    );

    await import('./index.js');

    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  it('dispatches start when the command entry point asks it to', async () => {
    const { runCli } = await import('./index.js');

    await runCli(['start']);

    expect(startMocks.runStartCommand).toHaveBeenCalledOnce();
  });

  it('dispatches stop with its own arguments (#394)', async () => {
    const { runCli } = await import('./index.js');

    await runCli(['stop', '--volumes']);

    expect(stopMocks.runStopCommand).toHaveBeenCalledWith(['--volumes']);
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  it('dispatches render with its own arguments (#422)', async () => {
    const { runCli } = await import('./index.js');

    await runCli(['render', 'acme-ai', '--check']);

    expect(renderMocks.runRenderCommand).toHaveBeenCalledWith(['acme-ai', '--check']);
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  it('dispatches doctor with its directory and flags (#423)', async () => {
    const { runCli } = await import('./index.js');

    await runCli(['doctor', 'acme-ai', '--json']);

    expect(doctorMocks.runDoctorCommand).toHaveBeenCalledWith(['acme-ai', '--json']);
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  it('dispatches deploy and exits 2 only for changes it was not told to apply (#430)', async () => {
    const { runCli } = await import('./index.js');

    expect(await runCli(['deploy', 'acme-ai'])).toBe(0);
    expect(deployMocks.runDeployCommand).toHaveBeenCalledWith(['acme-ai']);

    deployMocks.runDeployCommand.mockResolvedValueOnce({ changes: true, applied: false });
    expect(await runCli(['deploy', 'acme-ai'])).toBe(2);

    deployMocks.runDeployCommand.mockResolvedValueOnce({ changes: true, applied: true });
    expect(await runCli(['deploy', 'acme-ai', '--yes'])).toBe(0);
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  /**
   * `agent-workspace valdiate acme-ai` used to return silently and exit 0. In a deploy pipeline
   * that reads as a validation gate that passed, which is the one outcome the command exists to
   * make impossible — so an unrecognised verb is a usage error the process exits 1 on.
   */
  it('refuses an unrecognised verb with a non-zero exit instead of passing silently', async () => {
    const { runCli } = await import('./index.js');
    const { runAsProcess } = await import('./cli-failure.js');
    const stderr: string[] = [];

    const code = await runAsProcess(
      async () => {
        await runCli(['valdiate', 'acme-ai']);
      },
      (chunk) => stderr.push(chunk),
    );

    expect(code).toBe(1);
    expect(stderr.join('')).toContain('Unknown command "valdiate"');
    expect(stderr.join('')).toContain(
      'Usage: agent-workspace start|stop|validate|render|doctor|deploy',
    );
    expect(stderr.join('')).not.toContain('[directory]');
    expect(startMocks.runStartCommand).not.toHaveBeenCalled();
  });

  it('refuses an empty invocation the same way', async () => {
    const { runCli } = await import('./index.js');
    const { runAsProcess } = await import('./cli-failure.js');
    const stderr: string[] = [];

    expect(
      await runAsProcess(
        async () => {
          await runCli([]);
        },
        (chunk) => stderr.push(chunk),
      ),
    ).toBe(1);
    expect(stderr.join('')).toContain('agent-workspace needs a command');
  });

  it('recognizes direct and package-bin-style symlink entry paths', async () => {
    const sourceEntry = fileURLToPath(new URL('./index.ts', import.meta.url));
    const parent = await mkdtemp(path.join(os.tmpdir(), 'agent-workspace-cli-entry-'));
    created.push(parent);
    const symlinkEntry = path.join(parent, 'agent-workspace.ts');
    await symlink(sourceEntry, symlinkEntry, 'file');
    const { isMainModule } = await import('./index.js');

    expect(isMainModule(sourceEntry, new URL('./index.ts', import.meta.url).href)).toBe(true);
    expect(isMainModule(symlinkEntry, new URL('./index.ts', import.meta.url).href)).toBe(true);
  });
});
