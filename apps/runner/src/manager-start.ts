const noAgentStart = (): never => {
  throw new Error('runner manager proxies the runtime HTTP contract directly');
};

type DriverOptions = Pick<
  RunnerManagerOptions,
  | 'driver'
  | 'expectedDriver'
  | 'runtimeOrigin'
  | 'runtimeRequestUrl'
  | 'runtimeAuthHeaders'
  | 'configurationFingerprint'
  | 'readinessPath'
  | 'toolSandboxes'
  | 'toolSandboxRefusal'
> &
  Readonly<{
    /**
     * Remove every sandbox this manager owns, on shutdown (issue #394). Only the Docker driver
     * sets it: its sandboxes are containers beside the manager's own, on a network `docker compose
     * down` cannot remove while they hold it. A cloud driver's sandboxes outlive a manager replica
     * by design and expire on their own.
     */
    reap?: () => Promise<DockerReapReport>;
  }>;

/**
 * The Compose project the manager runs in, from `COMPOSE_PROJECT_NAME` (the generated
 * `compose.yaml` passes it). `undefined` when unset or blank, so a manager outside Compose labels
 * nothing; a malformed value is refused by the driver at start-up.
 */
export function composeProjectFor(
  env: Readonly<Record<string, string | undefined>>,
): string | undefined {
  const value = env['COMPOSE_PROJECT_NAME']?.trim();
  return value === undefined || value.length === 0 ? undefined : value;
}

/** The port the `tool-host` image listens on. */
const TOOL_HOST_PORT = 8788;

/** Where the gateway reaches a tool sandbox: its container name on the tool network. */
export function dockerToolSandboxOrigin(handle: RuntimeHandle): string {
  return `http://${dockerRuntimeName(handle.id)}:${String(TOOL_HOST_PORT)}`;
}

export function dockerRuntimeOrigin(handle: RuntimeHandle): string {
  // Docker's embedded DNS registers the assigned container name (and a shortened ID), not the
  // 64-character ID printed by `docker run`. Address the exact name generated by the driver.
  return `http://${dockerRuntimeName(handle.id)}:8080`;
}

/**
 * The `engine → image` map this manager starts sandboxes from (ENG-07, #306).
 *
 * Parsed once, at start-up, and never re-read: a malformed map must stop a manager from coming up
 * rather than surface as a failed run an hour later, and `readEngineImageMap` is the same parser the
 * control plane uses to decide `installed`. The two processes therefore cannot disagree about which
 * engines this deployment offers — which is the whole reason the parser lives in
 * `packages/runtime` rather than in either application.
 *
 * An empty map is legal for the parser, and a driver built over one refuses every `create()`; a
 * runner manager whose driver takes an image, though, can serve no run without one. It therefore
 * refuses to start rather than come up healthy and fail every allocation (ADR-0015). The guard
 * lives here and not in the drivers, whose total `create()` the `no-image-at-all` replay vector
 * pins.
 */
export function engineImagesFor(
  env: Readonly<Record<string, string | undefined>>,
  requireDigest: boolean = env['NODE_ENV'] === 'production',
): EngineImageMap {
  const images = readEngineImageMap(env, {
    knownEngineIds: ADAPTER_ENGINE_IDS,
    requireDigest,
    source: 'runner manager environment',
  });
  if (images.size === 0) {
    throw new EngineImageConfigurationError(
      'runner manager: no engine runtime image is configured; set AGENT_WORKSPACE_RUNTIME_IMAGE_<ENGINE> for at least one engine, or the legacy RUNTIME_IMAGE for claude-agent-sdk.',
      [],
    );
  }
  return images;
}

/**
 * A fingerprint over the whole map, so the control plane's Test Runtime approval is invalidated
 * when *any* engine's image changes rather than only when the first one does.
 */
function imagesFingerprint(images: EngineImageMap): string {
  return [...images]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([engine, image]) => `${engine}=${image}`)
    .join(',');
}

/**
 * `RUNTIME_PUBLISH=loopback`: this manager runs on the host, not on its sandboxes' network, so each
 * sandbox's port is published on `127.0.0.1` and addressed there. The local runtime's
 * `aw dev --sandbox docker` sets it (#786). Unset or blank, sandboxes are addressed by name.
 */
function dockerPublishFor(
  env: Readonly<Record<string, string | undefined>>,
): 'loopback' | undefined {
  const value = env['RUNTIME_PUBLISH']?.trim() ?? '';
  if (value === '') return undefined;
  if (value === 'loopback') return value;
  throw new Error('runner manager: RUNTIME_PUBLISH must be loopback, or unset.');
}

/** Exported for the suite, which passes a fake `docker`; production runs the real binary. */
export function dockerDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
  docker?: DockerCommand,
): DriverOptions {
  const images = engineImagesFor(env);
  const composeProject = composeProjectFor(env);
  const publish = dockerPublishFor(env);
  const egressProxyImage = env['AGENT_WORKSPACE_EGRESS_PROXY_IMAGE']?.trim();
  const proxyBypass = (env['RUNTIME_PROXY_BYPASS'] ?? '')
    .split(',')
    .map((host) => host.trim())
    .filter((host) => host.length > 0);
  const driver = createDockerDriver<never, never>({
    images,
    requireDigest: env['NODE_ENV'] === 'production',
    networkName: env['RUNTIME_NETWORK'] ?? 'agent-egress',
    workspaceStorage: 'anonymous-volume',
    startAgent: noAgentStart,
    ...(egressProxyImage === undefined || egressProxyImage === ''
      ? {}
      : { egressProxyImage, proxyBypass }),
    ...(composeProject === undefined ? {} : { composeProject }),
    ...(publish === undefined ? {} : { publish }),
    ...(docker === undefined ? {} : { docker }),
  });
  // ADR-0118 TS2: a second driver instance places the tool sandbox, on a network of its own that
  // the gateway shares and the agent sandboxes do not. Unset, a run that needs one is refused.
  const toolHostImage = env['AGENT_WORKSPACE_TOOL_HOST_IMAGE']?.trim();
  const toolDriver =
    toolHostImage === undefined || toolHostImage === ''
      ? undefined
      : createDockerDriver<never, never>({
          images: new Map([[TOOL_SANDBOX_ENGINE, toolHostImage]]),
          requireDigest: env['NODE_ENV'] === 'production',
          networkName: env['AGENT_WORKSPACE_TOOL_NETWORK'] ?? 'agent-workspace-tool-sandbox',
          workspaceStorage: 'anonymous-volume',
          startAgent: noAgentStart,
          // TS5: the egress proxy is the tool sandbox's only route out, so no proxy bypass.
          ...(egressProxyImage === undefined || egressProxyImage === ''
            ? {}
            : { egressProxyImage }),
          ...(composeProject === undefined ? {} : { composeProject }),
          ...(docker === undefined ? {} : { docker }),
        });
  return {
    driver,
    reap: async () => {
      const agents = await driver.reapAll();
      const tools = await toolDriver?.reapAll();
      return tools === undefined
        ? agents
        : {
            removed: [...agents.removed, ...tools.removed],
            failed: [...agents.failed, ...tools.failed],
          };
    },
    ...(toolDriver === undefined
      ? {}
      : {
          toolSandboxes: createToolSandboxes({
            driver: toolDriver,
            origin: dockerToolSandboxOrigin,
          }),
        }),
    runtimeOrigin:
      publish === undefined ? dockerRuntimeOrigin : (handle) => driver.publishedOrigin(handle),
    configurationFingerprint: `docker:${imagesFingerprint(images)}${
      egressProxyImage === undefined || egressProxyImage === '' ? '' : `+proxy=${egressProxyImage}`
    }${toolHostImage === undefined || toolHostImage === '' ? '' : `+tools=${toolHostImage}`}`,
  };
}

export function acaSessionsNetworkStatus(
  env: Readonly<Record<string, string | undefined>>,
): 'EgressEnabled' | 'EgressDisabled' {
  const value = env['ACA_SESSION_POOL_NETWORK_STATUS'] ?? 'EgressDisabled';
  if (value === 'EgressEnabled' || value === 'EgressDisabled') return value;
  throw new Error('ACA_SESSION_POOL_NETWORK_STATUS must be EgressEnabled or EgressDisabled');
}

/**
 * `RUNTIME_DRIVER=aca-sessions` routes the runtime contract through one pre-provisioned custom
 * container dynamic-session pool. The pool, rather than this process, owns image selection,
 * Hyper-V isolation, network mode, scale-to-zero, and session expiry.
 *
 * Two provider limitations are intentionally visible here. ACA network policy is a pool-wide
 * all-or-nothing setting, so one manager cannot promise both `none` and `open` profiles. Timed
 * sessions also expose an idle cooldown but no documented hard maximum lifetime, which is why the
 * driver reports `maxSessionSeconds: null`; application run timeouts remain the hard bound.
 *
 * The manager's allocation registry is process-local. Azure deployments must cap it at one active
 * replica, and a replica replacement invalidates manager URLs already returned to callers even
 * though ACA may keep those sessions alive until their idle timeout. The stable HMAC identifier
 * derived from `RUNNER_MANAGER_TOKEN` prevents tenant/session names from entering Azure routing
 * and lets a subsequent allocation request find the same provider session, but it is not a
 * substitute for a durable allocation registry.
 */
export function acaSessionsDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
): DriverOptions {
  const poolManagementEndpoint = env['ACA_SESSION_POOL_ENDPOINT'] ?? '';
  const apiVersion =
    env['ACA_SESSION_POOL_API_VERSION'] ??
    env['ACA_SESSION_API_VERSION'] ??
    ACA_SESSIONS_MANAGEMENT_API_VERSION;
  const networkStatus = acaSessionsNetworkStatus(env);
  const identifierSecret = env['RUNNER_MANAGER_TOKEN'] ?? '';
  // ENG-07: one ACA session pool is provisioned with one container image, so it offers exactly one
  // engine and a run for any other is refused before an allocation is made (ADR-0073 D6). The pool's
  // engine is configured rather than inferred: nothing in the management API reports which adapter
  // the pool's image carries. The default is spelled out, not taken from the adapter list, so adding
  // an adapter whose id sorts first cannot silently change what an existing pool claims to carry.
  const engine = env['ACA_SESSION_POOL_ENGINE'] ?? 'claude-agent-sdk';
  const client = createAcaSessionsRestClient({
    poolManagementEndpoint,
    apiVersion,
    getAccessToken: fetchAcaSessionsAccessToken,
  });
  const driver = createAcaSessionsDriver<never, never>({
    poolManagementEndpoint,
    networkStatus,
    engine,
    identifierSecret,
    client,
    startAgent: noAgentStart,
  });
  return {
    driver,
    expectedDriver: 'aca-sessions',
    runtimeRequestUrl: (handle, requestPath) => driver.requestUrl(handle, requestPath),
    runtimeAuthHeaders: async () => ({
      authorization: `Bearer ${await fetchAcaSessionsAccessToken()}`,
    }),
    configurationFingerprint: `aca-sessions:${poolManagementEndpoint}:${apiVersion}:${networkStatus}:${engine}`,
    readinessPath: '/ping',
  };
}

/**
 * `RUNTIME_DRIVER=cloud-run-service` deploys one private Cloud Run v2 service per session instead
 * of one Docker container. See `docs/adr/ADR-cloud-run-service-driver.md` and
 * `packages/runtime/src/cloud-run.ts` for why this exists in place of the spec's aspirational
 * `cloud-run-sandbox` driver.
 */
function cloudRunDriverOptions(env: Readonly<Record<string, string | undefined>>): DriverOptions {
  const images = engineImagesFor(env);
  const project = env['GCP_PROJECT'] ?? '';
  const region = env['GCP_REGION'] ?? '';
  const serviceAccount = env['RUNTIME_SERVICE_ACCOUNT'] ?? '';
  const vpcConnector = env['RUNTIME_VPC_CONNECTOR'];
  const client = createCloudRunAdminClient({ accessToken: fetchCloudRunAccessToken });
  return {
    driver: createCloudRunDriver<never, never>({
      images,
      project,
      region,
      serviceAccount,
      requireDigest: env['NODE_ENV'] === 'production',
      egress: env['RUNTIME_EGRESS'] === 'open' ? 'open' : 'none',
      ...(vpcConnector === undefined ? {} : { vpcConnector }),
      client,
      startAgent: noAgentStart,
    }),
    expectedDriver: 'cloud-run-service',
    runtimeOrigin: (handle) => handle.externalId,
    runtimeAuthHeaders: async (handle) => ({
      authorization: `Bearer ${await fetchCloudRunIdentityToken(handle.externalId)}`,
    }),
    configurationFingerprint: `cloud-run-service:${imagesFingerprint(images)}`,
    // Google Cloud's edge intercepts the literal path `/healthz` on a *.a.run.app default domain
    // and never reaches the container — see `readinessPath` on `RunnerManagerOptions` and
    // docs/adr/ADR-cloud-run-service-driver.md. `/ping` is the same liveness handler, mounted at a
    // second path the edge does not reserve.
    readinessPath: '/ping',
  };
}

/**
 * `RUNNER_MANAGER_STATELESS=true` (ADR-0126): the manager keeps no allocation table, so a Vercel
 * Function can serve it. The seal secret is `RUNNER_MANAGER_TOKEN`; the driver derives separate
 * keys from it. Only the two drivers whose provider can find a session's sandbox again support it.
 */
function sealSecretFor(
  env: Readonly<Record<string, string | undefined>>,
  driver: 'external' | 'vercel-sandbox',
): { sealSecret?: string } {
  const flag = env['RUNNER_MANAGER_STATELESS']?.trim() ?? '';
  if (flag === '') return {};
  if (flag !== 'true') {
    throw new Error('runner manager: RUNNER_MANAGER_STATELESS must be true, or unset.');
  }
  const secret = env['RUNNER_MANAGER_TOKEN'] ?? '';
  if (secret.length < 32) {
    throw new Error(
      `runner manager: RUNNER_MANAGER_TOKEN must contain at least 32 characters when RUNNER_MANAGER_STATELESS is true (${driver}).`,
    );
  }
  return { sealSecret: secret };
}

/**
 * ADR-0132's backstop for a tool sandbox no close reached: it ends this many seconds after the
 * last run that opened it. 15 minutes unless `AGENT_WORKSPACE_TOOL_SANDBOX_TIMEOUT_SECONDS` says
 * otherwise, from one minute to one hour.
 */
export function toolSandboxTimeoutSeconds(
  env: Readonly<Record<string, string | undefined>>,
): number {
  const text = env['AGENT_WORKSPACE_TOOL_SANDBOX_TIMEOUT_SECONDS']?.trim() || '900';
  const seconds = /^\d+$/u.test(text) ? Number(text) : Number.NaN;
  if (!Number.isInteger(seconds) || seconds < 60 || seconds > 3_600) {
    throw new Error(
      'runner manager: AGENT_WORKSPACE_TOOL_SANDBOX_TIMEOUT_SECONDS must be an integer from 60 through 3600, or unset.',
    );
  }
  return seconds;
}

/**
 * How long a session's agent-runtime sandbox may sit idle before its provider ends it. It stays
 * above the longest run a host allows (285 s on Vercel, 885 s on Cloudflare), so no run is cut,
 * and a crashed or abandoned session frees its slot instead of holding it for the plan maximum.
 */
const AGENT_RUNTIME_IDLE_SECONDS = 900;

/**
 * `RUNTIME_DRIVER=external` with `EXTERNAL_PROVIDER=e2b` (ADR-0120 LC1-LC6): one E2B sandbox per
 * session, reached at its public URL with a per-sandbox bearer. The provider key is not read here:
 * a caller sends it with each request (LC6). `GATEWAY_PUBLIC_URL` is the sandbox-facing gateway
 * URL; its host is the only one a `none` sandbox may reach (LC3, LC4).
 */
export function externalDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
): DriverOptions {
  const provider = env['EXTERNAL_PROVIDER']?.trim() ?? '';
  if (provider !== 'e2b') {
    throw new Error(
      'runner manager: EXTERNAL_PROVIDER must be e2b when RUNTIME_DRIVER is external.',
    );
  }
  const tier = env['E2B_PLAN_TIER']?.trim() || 'hobby';
  if (tier !== 'hobby' && tier !== 'pro') {
    throw new Error('runner manager: E2B_PLAN_TIER must be hobby or pro, or unset.');
  }
  const gatewayUrl = env['GATEWAY_PUBLIC_URL']?.trim() ?? '';
  // A template is `<name>:<build_id>`, not a digest (LC2), so the digest rule does not apply.
  const images = engineImagesFor(env, false);
  if (env['NODE_ENV'] === 'production') assertBuildIdPinnedTemplates(images);
  const driver = createExternalDriver<never, never>({
    provider: createE2bProvider({ tier }),
    images,
    gatewayUrl,
    startAgent: noAgentStart,
    sessionIdleSeconds: AGENT_RUNTIME_IDLE_SECONDS,
    ...sealSecretFor(env, 'external'),
  });
  const base = {
    driver,
    expectedDriver: 'external',
    runtimeRequestUrl: (handle: RuntimeHandle, requestPath: string) =>
      driver.requestUrl(handle, requestPath),
    runtimeAuthHeaders: (handle: RuntimeHandle) => driver.authHeaders(handle),
  } as const;
  // ADR-0120 LC5: the tool sandbox is a second `create()` on the same provider, from a template of
  // the tool-host image. Unset, a run that needs one is refused by name.
  const toolHostTemplate = env['AGENT_WORKSPACE_TOOL_HOST_IMAGE']?.trim() ?? '';
  if (toolHostTemplate === '') {
    return {
      ...base,
      configurationFingerprint: `external:e2b:${tier}:${imagesFingerprint(images)}`,
      toolSandboxRefusal:
        'a tool sandbox is not started on the external runtime: set AGENT_WORKSPACE_TOOL_HOST_IMAGE to the tool-host E2B template (ADR-0120 LC5)',
    };
  }
  const toolImages: EngineImageMap = new Map([[TOOL_SANDBOX_ENGINE, toolHostTemplate]]);
  if (env['NODE_ENV'] === 'production') assertBuildIdPinnedTemplates(toolImages);
  const toolDriver = createExternalDriver<never, never>({
    provider: createE2bProvider({ tier }),
    images: toolImages,
    gatewayUrl,
    startAgent: noAgentStart,
    workload: 'tool-host',
    ...sealSecretFor(env, 'external'),
  });
  return {
    ...base,
    configurationFingerprint: `external:e2b:${tier}:${imagesFingerprint(images)}+tools=${toolHostTemplate}`,
    toolSandboxes: createToolSandboxes({
      driver: toolDriver,
      driverId: 'external',
      // The manager serves the sandbox's /mcp, so the provider's access token stays here.
      origin: (handle, publicBase) => `${publicBase}/tool-sandboxes/${handle.id}`,
      upstream: (handle) => ({
        url: toolDriver.requestUrl(handle, '/mcp'),
        headers: toolDriver.accessHeaders(handle),
      }),
      recover: (id) => toolDriver.recover?.(id),
      timeoutSeconds: toolSandboxTimeoutSeconds(env),
    }),
  };
}

/**
 * `RUNTIME_DRIVER=cloudflare-sandbox` (ADR-0120 LC1-LC4, LC6): one Cloudflare Container per session
 * behind the bridge Worker at `CLOUDFLARE_SANDBOX_BRIDGE_URL`. The bridge secret is not read here: a
 * caller sends it with each request (LC6). Images keep their digest pin in production (LC2).
 */
export function cloudflareSandboxDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
): DriverOptions {
  const bridgeUrl = env['CLOUDFLARE_SANDBOX_BRIDGE_URL']?.trim() ?? '';
  if (!bridgeUrl.startsWith('https://') || !URL.canParse(bridgeUrl)) {
    throw new Error(
      'runner manager: CLOUDFLARE_SANDBOX_BRIDGE_URL must be an https URL when RUNTIME_DRIVER is cloudflare-sandbox.',
    );
  }
  const images = engineImagesFor(env);
  const driver = createCloudflareSandboxDriver<never, never>({
    bridgeUrl,
    images,
    gatewayUrl: env['GATEWAY_PUBLIC_URL']?.trim() ?? '',
    startAgent: noAgentStart,
  });
  return {
    driver,
    expectedDriver: 'cloudflare-sandbox',
    runtimeRequestUrl: (handle, requestPath) => driver.requestUrl(handle, requestPath),
    runtimeAuthHeaders: (handle) => driver.authHeaders(handle),
    configurationFingerprint: `cloudflare-sandbox:${imagesFingerprint(images)}`,
    toolSandboxRefusal:
      'a tool sandbox is not started on the cloudflare-sandbox runtime yet (ADR-0120 LC5)',
  };
}

/**
 * `RUNTIME_DRIVER=vercel-sandbox` (ADR-0120 LC1-LC4, LC6): one Vercel Sandbox microVM per session,
 * reached at its exposed-port URL with a per-sandbox bearer. It runs on the `external` driver's
 * implementation under its own driver id. The access token is not read here: a caller sends it with
 * each request (LC6). The team and project ids are identifiers, not secrets.
 */
export function vercelSandboxDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
): DriverOptions {
  const tier = env['VERCEL_PLAN_TIER']?.trim() || 'hobby';
  if (tier !== 'hobby' && tier !== 'pro') {
    throw new Error('runner manager: VERCEL_PLAN_TIER must be hobby or pro, or unset.');
  }
  const identifier = (name: 'VERCEL_TEAM_ID' | 'VERCEL_PROJECT_ID'): string => {
    // `AW_<NAME>` first: Vercel reserves the VERCEL_ prefix for its own variables, so a deploy
    // sets the team id under the other name.
    const value = (env[`AW_${name}`] ?? env[name])?.trim() ?? '';
    if (!/^[A-Za-z0-9_-]{1,128}$/u.test(value)) {
      throw new Error(`runner manager: ${name} must be set when RUNTIME_DRIVER is vercel-sandbox.`);
    }
    return value;
  };
  const teamId = identifier('VERCEL_TEAM_ID');
  const projectId = identifier('VERCEL_PROJECT_ID');
  const gatewayUrl = env['GATEWAY_PUBLIC_URL']?.trim() ?? '';
  // LC2: the image is a digest-pinned reference in Vercel Container Registry, so the digest rule of
  // the other image-pinned drivers applies in production.
  const images = engineImagesFor(env);
  const driver = createExternalDriver<never, never>({
    provider: createVercelSandboxProvider({ teamId, projectId, tier }),
    driverId: 'vercel-sandbox',
    images,
    gatewayUrl,
    startAgent: noAgentStart,
    ...sealSecretFor(env, 'vercel-sandbox'),
  });
  return {
    driver,
    expectedDriver: 'vercel-sandbox',
    runtimeRequestUrl: (handle, requestPath) => driver.requestUrl(handle, requestPath),
    runtimeAuthHeaders: (handle) => driver.authHeaders(handle),
    configurationFingerprint: `vercel-sandbox:${tier}:${teamId}:${projectId}:${imagesFingerprint(images)}`,
    toolSandboxRefusal:
      'a tool sandbox is not started on the vercel-sandbox runtime: the restricted network policy a tool sandbox with allowedDomains needs is refused until the E7 proof (ADR-0120 LC4, LC5)',
  };
}

/** The field manager every object the kubernetes driver creates is recorded under. */
export const KUBERNETES_FIELD_MANAGER = 'agent-workspace-runner-manager';

/**
 * `RUNTIME_DRIVER=kubernetes`: one sandbox Pod per session, created in the manager's own namespace
 * with the ServiceAccount credentials the cluster mounts into this pod (never a kubeconfig). The
 * chart gives the manager a namespaced Role, so the driver runs in shared-namespace mode: it creates
 * no Namespace and each session gets a Service the manager reaches it by.
 *
 * The manager's allocation registry is process-local, so the chart runs exactly one replica. `client`
 * is for the suite; production leaves it unset.
 */
export function kubernetesDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
  client?: KubernetesResourceClient,
): DriverOptions {
  const required = (name: string): string => {
    const value = env[name]?.trim() ?? '';
    if (value === '') {
      throw new Error(`runner manager: ${name} must be set when RUNTIME_DRIVER is kubernetes.`);
    }
    return value;
  };
  const namespace = required('RUNTIME_KUBERNETES_NAMESPACE');
  const gatewayService = required('RUNTIME_GATEWAY_SERVICE');
  if (client === undefined && (env['KUBERNETES_SERVICE_HOST']?.trim() ?? '') === '') {
    throw new Error(
      'runner manager: RUNTIME_DRIVER=kubernetes needs the in-cluster ServiceAccount; run it in a pod.',
    );
  }
  const images = engineImagesFor(env);
  const egressProxyImage = env['AGENT_WORKSPACE_EGRESS_PROXY_IMAGE']?.trim() ?? '';
  const runtimeClassName = env['RUNTIME_CLASS_NAME']?.trim() ?? '';
  const proxyBypass = (env['RUNTIME_PROXY_BYPASS'] ?? '')
    .split(',')
    .map((host) => host.trim())
    .filter((host) => host.length > 0);
  const driver = createKubernetesDriver<never, never>({
    images,
    namespace,
    gatewayService,
    fieldManager: KUBERNETES_FIELD_MANAGER,
    requireDigest: env['NODE_ENV'] === 'production',
    client: client ?? inClusterKubernetesClient(),
    startAgent: noAgentStart,
    ...(egressProxyImage === '' ? {} : { egressProxyImage, proxyBypass }),
    ...(runtimeClassName === '' ? {} : { runtimeClassName }),
  });
  return {
    driver,
    expectedDriver: 'kubernetes',
    runtimeOrigin: kubernetesRuntimeOrigin,
    configurationFingerprint: `kubernetes:${namespace}:${imagesFingerprint(images)}${
      egressProxyImage === '' ? '' : `+proxy=${egressProxyImage}`
    }`,
    toolSandboxRefusal:
      'a tool sandbox is not started on the kubernetes runtime: its placement is a follow-up of #854',
  };
}

/** `externalId` is `<namespace>/<pod>`; the Service the driver creates carries the pod's name. */
export function kubernetesRuntimeOrigin(handle: RuntimeHandle): string {
  const [namespace, pod] = handle.externalId.split('/');
  if (namespace === undefined || pod === undefined || pod === '') {
    throw new Error('runner manager: a kubernetes handle names a namespace and a pod.');
  }
  return `http://${pod}.${namespace}.svc:8080`;
}

const SERVED_RUNTIME_DRIVERS = [
  'docker',
  'cloud-run-service',
  'aca-sessions',
  'external',
  'vercel-sandbox',
  'cloudflare-sandbox',
  'kubernetes',
] as const;

/**
 * A `RUNTIME_DRIVER` this manager does not serve (#818). It is refused before any driver is built,
 * because falling back to Docker would run sandboxes under a different label than the operator
 * chose. The message names the served ids and not the value; `driver` carries the value for logs.
 */
export class RuntimeDriverConfigurationError extends Error {
  constructor(readonly driver: string) {
    super(
      `runner manager: RUNTIME_DRIVER is not a driver this manager serves; use one of ${SERVED_RUNTIME_DRIVERS.join(', ')}, or leave it unset for docker.`,
    );
    this.name = 'RuntimeDriverConfigurationError';
  }
}

/** Exported for the suite. Unset or blank selects Docker; an id the manager does not serve throws. */
export function managerDriverOptions(
  env: Readonly<Record<string, string | undefined>>,
  docker?: DockerCommand,
): DriverOptions {
  const driver = env['RUNTIME_DRIVER']?.trim() ?? '';
  if (driver === 'external') return externalDriverOptions(env);
  if (driver === 'vercel-sandbox') return vercelSandboxDriverOptions(env);
  if (env['RUNNER_MANAGER_STATELESS']?.trim()) {
    throw new Error(
      'runner manager: RUNNER_MANAGER_STATELESS is served by the external and vercel-sandbox drivers only (ADR-0126).',
    );
  }
  if (driver === 'cloud-run-service') return cloudRunDriverOptions(env);
  if (driver === 'aca-sessions') return acaSessionsDriverOptions(env);
  if (driver === 'cloudflare-sandbox') return cloudflareSandboxDriverOptions(env);
  if (driver === '' || driver === 'docker') return dockerDriverOptions(env, docker);
  if (driver === 'kubernetes') return kubernetesDriverOptions(env);
  throw new RuntimeDriverConfigurationError(driver);
}

/** The manager's options from its environment, and the Docker reap a shutdown runs (if any). */
export function runnerManagerOptionsFromEnvironment(
  env: Readonly<Record<string, string | undefined>>,
): { options: RunnerManagerOptions; reap: DriverOptions['reap'] } {
  const { reap, ...driverOptions } = managerDriverOptions(env);
  const verificationTimeoutMs = env['RUNTIME_VERIFICATION_TIMEOUT_MS'];
  return {
    reap,
    options: {
      token: env['RUNNER_MANAGER_TOKEN'] ?? '',
      workspacesRoot: env['RUNTIME_WORKSPACES_ROOT'] ?? '/var/lib/agent-workspace/runtimes',
      ...driverOptions,
      ...(verificationTimeoutMs === undefined
        ? {}
        : { verificationTimeoutMs: Number(verificationTimeoutMs) }),
    },
  };
}

export async function startRunnerManager(
  env: Readonly<Record<string, string | undefined>> = process.env,
) {
  const { options, reap } = runnerManagerOptionsFromEnvironment(env);
  // Every create goes through the gate, so a shutdown can refuse new ones and wait for the rest.
  const gate = createShutdownGate(options.driver);
  const server = createRunnerManagerServer({ ...options, driver: gate.driver });
  const host = env['HOST'] ?? '0.0.0.0';
  // `0` asks the OS for a free port; the embedded local runtime does, and reads `address.port`.
  const port = env['PORT']?.trim() === '0' ? 0 : parsePort(env['PORT'] ?? '8090');
  const address = await listen(server, port, host);
  return {
    server,
    address,
    shutdown: () => shutdownRunnerManager(server, reap, process.stderr, gate),
  };
}

/**
 * How long a shutdown waits for in-flight sandbox creates before it reaps: well inside the 30 s
 * stop grace period the generated `compose.yaml` gives the runner, leaving time for the reap.
 */
export const IN_FLIGHT_SETTLE_TIMEOUT_MS = 15_000;

/** How the shutdown went: `clean` only when every owned sandbox was positively removed. */
export type ManagerShutdownOutcome = 'clean' | 'sandboxes-left';

/**
 * Stop serving and remove this manager's sandboxes (issue #394).
 *
 * `docker compose down` stops the manager with `SIGTERM` and then removes the project's networks.
 * A sandbox still attached to `<project>-runtime-control` keeps that network, and itself, alive
 * after `down` reports success, so the manager removes them first. New requests are refused from
 * the first step; open proxied streams end when their sandbox is removed, and are then closed. A
 * sandbox that could not be removed is named on stderr and reported as `sandboxes-left`, never
 * read as a clean stop (ADR-0015); `agent-workspace stop` removes it by its labels.
 *
 * Before the reap, the gate refuses new creates and waits up to `settleTimeoutMs` for those in
 * flight. A create still running when that wait ends may start a sandbox after the reap, or after
 * this process has exited, so the outcome is then `sandboxes-left`, never `clean`.
 */
export async function shutdownRunnerManager(
  server: Server,
  reap: (() => Promise<DockerReapReport>) | undefined,
  log: Pick<NodeJS.WriteStream, 'write'> = process.stderr,
  gate?: Pick<ShutdownGate, 'close'>,
  settleTimeoutMs: number = IN_FLIGHT_SETTLE_TIMEOUT_MS,
): Promise<ManagerShutdownOutcome> {
  server.close();
  let outcome: ManagerShutdownOutcome = 'clean';
  // Refuse new sandboxes (503), and let the ones already being created finish before the reap
  // lists what exists.
  if (gate !== undefined && !(await gate.close(settleTimeoutMs))) {
    log.write(
      `runner manager: sandbox creation still in progress after ${String(settleTimeoutMs)}ms; ` +
        'removing what exists now, but a sandbox it starts later may be left: run ' +
        '`agent-workspace stop` to remove it\n',
    );
    outcome = 'sandboxes-left';
  }
  if (reap !== undefined) {
    try {
      const report = await reap();
      log.write(`runner manager: removed ${String(report.removed.length)} sandbox(es)\n`);
      for (const failure of report.failed) {
        log.write(`runner manager: could not remove ${failure.container}: ${failure.reason}\n`);
      }
      if (report.failed.length > 0) outcome = 'sandboxes-left';
    } catch (error) {
      log.write(
        `runner manager: sandbox removal failed: ${error instanceof Error ? error.message : String(error)}\n`,
      );
      outcome = 'sandboxes-left';
    }
  }
  server.closeAllConnections();
  return outcome;
}

const SHUTDOWN_SIGNALS = ['SIGINT', 'SIGTERM'] as const;

const invokedPath = process.argv[1];
if (invokedPath !== undefined && import.meta.url === pathToFileURL(invokedPath).href) {
  startRunnerManager()
    .then(({ address, shutdown }) => {
      process.stdout.write(
        `runner manager listening on ${address.address}:${String(address.port)}\n`,
      );
      let stopping = false;
      const stop = (signal: NodeJS.Signals): void => {
        if (stopping) {
          process.stderr.write(`runner manager: second ${signal}; leaving now\n`);
          process.exit(2);
        }
        stopping = true;
        process.stderr.write(`runner manager: ${signal} received; removing sandboxes\n`);
        void shutdown().then((outcome) => {
          process.exit(outcome === 'clean' ? 0 : 2);
        });
      };
      for (const signal of SHUTDOWN_SIGNALS) process.on(signal, stop);
    })
    .catch((error: unknown) => {
      process.stderr.write(
        `runner manager failed to start: ${error instanceof Error ? error.message : String(error)}\n`,
      );
      process.exitCode = 1;
    });
}
